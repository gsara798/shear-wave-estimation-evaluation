function tests=test_qmv2_experimental_risk_mask
% Read-only preflight and synthetic patch alignment tests; no local
% experiment data, mask checkpoints or raw IQ files required.
tests=functiontests(localfunctions);
end

function setupOnce(tc)
repo=string(fileparts(fileparts(mfilename("fullpath"))));
study=fullfile(repo,"studies","reqml_experimental_qmv2");
addpath(study,"-begin");
tc.TestData.manifest=fullfile(study,"experiment_manifest.example.json");
end

function testConfigHasFourDistinctFrozenMaskBundles(tc)
C=read_qmv2_experiment_manifest(tc.TestData.manifest);
verifyTrue(tc,isfield(C,"mask_transfer"));
S=C.mask_transfer;
verifyEqual(tc,string(S.analysis_version), ...
    "quality_mask_transfer_r14_q_ret80_v1");
verifyEqual(tc,double(S.target_retention),0.8);
verifyEqual(tc,double(S.risk_error_threshold),0.1);
verifyEqual(tc,string(S.mask_feature_set),"reduced14");
verifyFalse(tc,logical(S.include_frequency));
verifyEqual(tc,numel(S.arms),4);
arms=string({S.arms.arm});
verifyEqual(tc,numel(unique(arms)),4);
verifyTrue(tc,all(startsWith(arms,"qmv2_")));
verifyTrue(tc,all(endsWith(string({S.arms.mask_file}), ...
    "risk_mask_model.mat")));
end

function testScopedPlanIsReadOnlyAndFindsFrozenFiles(tc)
R=run_qmv2_experimental_risk_mask( ...
    ManifestFile=tc.TestData.manifest,Mode="plan", ...
    CaseIDs="2026Feb27_homo_10perc_sp", ...
    Arms=["qmv2_unfiltered_reduced14", ...
        "qmv2_unfiltered_expanded20"], ...
    FrequenciesHz=300);
verifyEqual(tc,R.status,"planned");
verifyEqual(tc,height(R.jobs),1);
verifyEqual(tc,height(R.models),2);
verifyEqual(tc,double(R.jobs.frequency_hz),300);
verifyTrue(tc,all(ismember(R.models.arm, ...
    ["qmv2_unfiltered_reduced14", ...
     "qmv2_unfiltered_expanded20"])));
verifyTrue(tc,all(contains(R.models.mask_file, ...
    "risk_mask_oof_v1")));
end

function testCannotUseBaselineNonQmv2Mask(tc)
verifyError(tc,@()run_qmv2_experimental_risk_mask( ...
    ManifestFile=tc.TestData.manifest, ...
    Arms="reduced14",Mode="plan"), ...
    "ExpQMV2:MaskArmSelection");
end

function testPatchAlignmentInvalidVsRejected(tc)
if exist("fitcensemble","file")~=2
    return
end
rngState=rng;
cleanup=onCleanup(@()rng(rngState)); %#ok<NASGU>
rng(14,"twister");
n=80;
trainX=[linspace(0,1,n)', ...
    .2+ .6*linspace(0,1,n)'];
trainY=double(trainX(:,1)>.5);
classifier=fitcensemble(trainX,trainY, ...
    Method="Bag",Learners=templateTree(MinLeafSize=2, ...
    Reproducible=true),NumLearningCycles=10,ClassNames=[0;1]);
[z,x]=ndgrid(1:4,1:5);
q=.2+.6*reshape(linspace(0,1,20),4,5);
valid=true(4,5);
valid(1,1)=false;
feature=reshape(linspace(0,1,20),4,5);
feature(2,2)=NaN;
map_iz=z(:);map_ix=x(:);
radial_entropy=feature(:);
examples=table(map_iz,map_ix,radial_entropy);
result=struct("patch_examples",examples, ...
    "q_map",q,"cs_map",2+zeros(4,5), ...
    "valid_mask",valid,"x_mm",1:5,"z_mm",(1:4)', ...
    "metadata",struct("model_provenance_id", ...
    "qmv2_unfiltered_reduced14","frequency_hz",500));
meta=struct("schema","qmv2_risk_mask_oof_v1", ...
    "filter_arm","unfiltered", ...
    "quantile_predictor_set","reduced14", ...
    "predictor_names",["radial_entropy";"qmv2_predicted_quantile"], ...
    "risk_probability_threshold",0.5, ...
    "risk_error_threshold",0.1,"target_retention",0.8, ...
    "test_used",false);
Q=qmv2_score_experimental_risk_mask( ...
    result,classifier,meta,"qmv2_unfiltered_reduced14");
verifyEqual(tc,Q.original_valid_count,19);
verifyEqual(tc,Q.unscored_count,1);
verifyTrue(tc,isnan(Q.risk_score_map(1,1)));
verifyTrue(tc,isnan(Q.risk_score_map(2,2)));
verifyTrue(tc,isnan(Q.masked_sws_map(1,1)));
verifyTrue(tc,isnan(Q.masked_sws_map(2,2)));
verifyEqual(tc,nnz(Q.retained_mask)+ ...
    nnz(Q.rejected_mask)+nnz(Q.unscored_mask), ...
    Q.original_valid_count);
verifyEqual(tc,Q.original_sws_map,2+zeros(4,5));
verifyTrue(tc,isequal(Q.q_map,q));
end

function testRejectsWrongQuantileArm(tc)
R=struct("patch_examples",table((1:2)',(1:2)', ...
    'VariableNames',["map_iz","map_ix"]), ...
    "q_map",ones(2),"cs_map",ones(2), ...
    "valid_mask",true(2),"x_mm",[1 2],"z_mm",[1;2], ...
    "metadata",struct("model_provenance_id", ...
    "qmv2_unfiltered_reduced14"));
meta=struct("schema","qmv2_risk_mask_oof_v1", ...
    "filter_arm","fixed_donut", ...
    "quantile_predictor_set","reduced14", ...
    "predictor_names","qmv2_predicted_quantile", ...
    "risk_probability_threshold",0.5, ...
    "risk_error_threshold",0.1,"target_retention",0.8, ...
    "test_used",false);
verifyError(tc,@()qmv2_score_experimental_risk_mask( ...
    R,[],meta,"qmv2_unfiltered_reduced14"), ...
    "ExpQMV2:MaskArm");
end
