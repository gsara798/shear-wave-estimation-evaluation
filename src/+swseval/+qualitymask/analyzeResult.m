function out=analyzeResult(result,bundleFile,options)
%ANALYZERESULT Transfer frozen Reduced14 SWS-error risk to an existing map.
% No experimental ground truth is inferred. The risk model was calibrated
% on unfiltered Q0-v5 synthetic fields at 750 Hz.
arguments
    result (1,1) struct
    bundleFile (1,1) string
    options.MaximumRisks (1,:) double = [0.2 0.3]
    options.Arm (1,1) string = "reduced14"
    options.RiskPredictor (1,1) function_handle = @q0v5.quality.predictRisk
end
cutoffs=sort(unique(options.MaximumRisks(:)));
assert(~isempty(cutoffs) && all(isfinite(cutoffs)) && ...
    all(cutoffs>=0 & cutoffs<=1),"QualityTransfer:Threshold", ...
    "MaximumRisks must contain values between 0 and 1.");
assert(ismember(options.Arm,["reduced14","reduced14_filtered"]), ...
    "QualityTransfer:Arm","Only frozen Reduced14 inference arms are supported.");
assert(isfile(bundleFile),"QualityTransfer:Bundle", ...
    "Missing frozen quality-mask bundle: %s",bundleFile);
b=load(bundleFile,"metadata");
assert(isfield(b,"metadata") && isfield(b.metadata,"predictors") && ...
    string(b.metadata.version)=="reduced14_quality_mask_v1", ...
    "QualityTransfer:BundleIdentity", ...
    "Expected frozen reduced14_quality_mask_v1 bundle.");
features=string(b.metadata.predictors(:));
assert(numel(features)==21 && features(end)=="quality_q_pred" && ...
    numel(unique(features))==21,"QualityTransfer:Predictors", ...
    "Expected 20 deployment-observable features plus quality_q_pred.");
required=["patch_examples","patch_predictions","cs_map","q_map", ...
    "valid_mask","x_mm","z_mm","metadata"];
assert(all(isfield(result,cellstr(required))),"QualityTransfer:Result", ...
    "Result must come from reqml.predictSWS with saved patch tables.");
e=result.patch_examples;
p=result.patch_predictions;
assert(istable(e) && istable(p) && height(e)==height(p) && ...
    all(ismember(["map_iz","map_ix"],string(e.Properties.VariableNames))) && ...
    all(ismember(["q_pred","cs_pred_m_s","sws_valid"], ...
    string(p.Properties.VariableNames))),"QualityTransfer:PatchRows", ...
    "Missing or mismatched aligned patch predictions.");
assert(isfield(result.metadata,"model_provenance_id") && ...
    string(result.metadata.model_provenance_id)== ...
        "reqml_q0_v5_localonly_reduced14_transfer_v1", ...
    "QualityTransfer:ModelIdentity", ...
    "Quality mask cannot be applied to a different SWS estimator.");
if isfield(result.metadata,"comparison_arm")
    assert(string(result.metadata.comparison_arm)==options.Arm, ...
        "QualityTransfer:ArmIdentity", ...
        "The stored estimator arm does not match the requested arm.");
end
missing=setdiff(features(1:end-1),string(e.Properties.VariableNames));
assert(isempty(missing),"QualityTransfer:MissingFeatures", ...
    "Prediction result lacks features: %s",strjoin(missing,", "));
sz=size(result.cs_map);
assert(numel(sz)==2 && isequal(size(result.q_map),sz) && ...
    isequal(size(result.valid_mask),sz) && ...
    numel(result.x_mm)==sz(2) && numel(result.z_mm)==sz(1), ...
    "QualityTransfer:MapShape","REQ result map/grid shape mismatch.");
iz=double(e.map_iz(:));ix=double(e.map_ix(:));
assert(all(isfinite(iz) & isfinite(ix)) && ...
    all(iz==round(iz) & ix==round(ix)) && ...
    all(iz>=1 & iz<=sz(1) & ix>=1 & ix<=sz(2)), ...
    "QualityTransfer:Indices","Invalid patch-to-map indices.");
linear=sub2ind(sz,iz,ix);
assert(numel(unique(linear))==height(e), ...
    "QualityTransfer:Duplicate","Repeated patch index in prediction map.");
q=double(p.q_pred(:)); cs=double(p.cs_pred_m_s(:));
qStored=double(result.q_map(linear));
csStored=double(result.cs_map(linear));
assert(isequaln(q,qStored) && isequaln(cs,csStored) && ...
    isequal(logical(p.sws_valid(:)),logical(result.valid_mask(linear))), ...
    "QualityTransfer:Alignment", ...
    "Stored patch predictions do not align exactly with SWS/Q maps.");
valid=logical(p.sws_valid(:)) & isfinite(cs) & cs>0;
observations=e(:,cellstr(features(1:end-1)));
observations.quality_q_pred=q;
X=double(observations{:,cellstr(features)});
finiteFeatures=all(isfinite(X),2) & isreal(X) & ...
    q>=0 & q<=1;
risk=nan(height(e),1);
if any(finiteFeatures)
    risk(finiteFeatures)=double(options.RiskPredictor( ...
        bundleFile,observations(finiteFeatures,:)));
end
assert(all(isfinite(risk(finiteFeatures)) & ...
    risk(finiteFeatures)>=0 & risk(finiteFeatures)<=1), ...
    "QualityTransfer:RiskRange","Model risk values must be in [0,1].");
% Invalid SWS is *always* discarded. Risk=1 here is a rejection sentinel,
% NOT a calibrated classifier probability for invalid/non-evaluable rows.
risk(~valid)=1;
nr=numel(cutoffs);
riskMap=nan(sz);riskMap(linear)=risk;
validMap=false(sz);validMap(linear)=valid;
originalSws=double(result.cs_map);originalSws(~validMap)=NaN;
masked=nan([sz nr]);
rows=cell(nr,1);
for k=1:nr
    keep=valid & isfinite(risk) & risk<=cutoffs(k);
    keepMap=false(sz);keepMap(linear)=keep;
    tmp=originalSws;tmp(~keepMap)=NaN;
    masked(:,:,k)=tmp;
    v=cs(keep);
    rows{k}=table(cutoffs(k),nnz(valid),nnz(valid & finiteFeatures), ...
        nnz(keep),nnz(keep)/max(nnz(valid),1), ...
        mean(v,"omitnan"),median(v,"omitnan"),std(v,"omitnan"), ...
        VariableNames=["max_risk","valid_count", ...
        "evaluable_valid_count","retained_count", ...
        "fraction_retained_valid","mean_sws_m_s", ...
        "median_sws_m_s","spatial_sd_sws_m_s"]);
end
out=struct("arm",options.Arm,"risk_map",riskMap, ...
    "original_sws_map",originalSws,"masked_sws_maps",masked, ...
    "valid_mask",validMap,"x_mm",double(result.x_mm(:)'), ...
    "z_mm",double(result.z_mm(:)),"max_risks",cutoffs, ...
    "risk_probability_per_patch",risk, ...
    "quality_model_evaluable_per_patch",finiteFeatures, ...
    "unscored_valid_count",nnz(valid & ~finiteFeatures), ...
    "summary",vertcat(rows{:}), ...
    "transfer_status","exploratory_750Hz_synthetic_to_experimental", ...
    "spatial_filter_transfer",options.Arm=="reduced14_filtered");
end
