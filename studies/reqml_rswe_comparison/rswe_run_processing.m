function out=rswe_run_processing(varargin)
%RUN_PROCESSING Run/resume EWP IQ processing and derived filtered wavefields.
% Usage: rswe_run_processing(); or rswe_run_processing(UseParallel=false);
c=rswe_comparison_config(varargin{:});
processAll(c,c);
out=struct("stage","process","experiments",c.Experiments, ...
    "raw_run",c.rawRun,"filtered_run",c.filteredRun);
end

function processAll(o,c)
assert(~isempty(which("ewp.runFrequencySweep")), ...
    "RSWECompare:EWP","EWP src is not accessible on MATLAB path.");
assert(~isempty(which("q0v5.filter.applyFixedDonut")), ...
    "RSWECompare:Donut","Q0-v5 global donut function is not available.");
for experiment=o.Experiments
    root=fullfile(o.DataRoot,experiment);
    rawFolder=fullfile(root,"raw");
    assert(isfolder(rawFolder),"RSWECompare:Raw", ...
        "Missing raw acquisition folder: %s",rawFolder);
    fprintf("\n=== PROCESS %s ===\n",experiment);
    % Single IQ-processing pass, no spatial filter, no SVD removal.
    ewp.runFrequencySweep( ...
        InputRoot=rawFolder, ...
        FilePattern=o.FilePattern, ...
        Frequencies=o.Frequencies, ...
        RunName=c.rawRun, ...
        SpatialFilterMode="none", ...
        DonutEnabled=false, ...
        RemoveSVDModes=0, ...
        MakeIsotropic=true, ...
        SaveFigures=false,SaveMovies=false, ...
        UseParallel=o.UseParallel,Resume=o.Resume);
    for f=o.Frequencies
        rawSample=sampleFile(root,c.rawRun,f);
        assert(isfile(rawSample),"RSWECompare:RawSample", ...
            "EWP did not produce %s",rawSample);
        derivedSample=sampleFile(root,c.filteredRun,f);
        makeFilteredSample(rawSample,derivedSample,c,o.Resume);
    end
end
end

function dest=sampleFile(root,runName,f)
dest=fullfile(root,"processed",runName, ...
    sprintf("%gHz",f),"wavefield_sample.mat");
end

function makeFilteredSample(sourceFile,dest,c,resume)
stamp=dir(sourceFile);
identity=struct("source_file",sourceFile, ...
    "source_bytes",double(stamp.bytes), ...
    "source_datenum",double(stamp.datenum), ...
    "filter","global_fft_donut_after_isotropic", ...
    "CsMinMS",c.csMin,"CsMaxMS",c.csMax, ...
    "TaperRelative",c.taper);
signature=string(jsonencode(identity));
folder=string(fileparts(dest));
manifest=fullfile(folder,"reqml_comparison_filter_manifest.mat");
if isfile(dest) || isfile(manifest)
    assert(resume && isfile(dest) && isfile(manifest), ...
        "RSWECompare:FilteredExists", ...
        "Existing filtered output cannot be overwritten: %s",dest);
    saved=load(manifest,"signature");
    assert(isfield(saved,"signature") && ...
        string(saved.signature)==signature, ...
        "RSWECompare:FilteredStale", ...
        "Existing filtered sample has a different source/config: %s",dest);
    fprintf("  %s: filter resumed\n",dest);
    return
end
z=load(sourceFile,"wavefield_sample");
assert(isfield(z,"wavefield_sample"),"RSWECompare:Schema", ...
    "Expected EWP wavefield_sample struct in %s",sourceFile);
wavefield_sample=z.wavefield_sample; %#ok<NASGU>
assert(isfield(wavefield_sample,"coordinates") && ...
    isfield(wavefield_sample,"wavefield") && ...
    isfield(wavefield_sample.wavefield,"data_zx"), ...
    "RSWECompare:Schema","Invalid EWP wavefield sample.");
assert(~isfield(wavefield_sample.provenance,"comparison_filter_v1"), ...
    "RSWECompare:DoubleFilter","Source sample already marked filtered.");
U=wavefield_sample.wavefield.data_zx;
fx=q0v5.filter.applyFixedDonut( ...
    U,double(wavefield_sample.coordinates.dx_m), ...
    double(wavefield_sample.coordinates.dz_m), ...
    double(wavefield_sample.wavefield.frequency_hz), ...
    CsMinMS=c.csMin,CsMaxMS=c.csMax,TaperRelative=c.taper);
wavefield_sample.wavefield.data_zx=fx.field_zx;
wavefield_sample.provenance.comparison_filter_v1=struct( ...
    "type","global_fft_donut_after_isotropic", ...
    "source_sample",sourceFile, ...
    "cs_min_m_s",c.csMin,"cs_max_m_s",c.csMax, ...
    "taper_relative",c.taper, ...
    "retained_power_fraction",fx.retained_energy_fraction);
if ~isfolder(folder),mkdir(folder);end
tmp=dest+".partial.mat";
assert(~isfile(tmp),"RSWECompare:Partial", ...
    "Inspect the interrupted output before rerunning: %s",tmp);
save(tmp,"wavefield_sample","-v7.3");
[ok,msg]=movefile(tmp,dest);
assert(ok,"RSWECompare:Write","Failed to save filtered sample: %s",msg);
retained_power_fraction=fx.retained_energy_fraction; %#ok<NASGU>
save(manifest,"signature","identity","retained_power_fraction");
fprintf("  %s: retained %.1f%% spectral power\n", ...
    string(fileparts(dest)),100*retained_power_fraction);
end
