function out=run_quality_mask_transfer(options)
%RUN_QUALITY_MASK_TRANSFER Analyze frozen Reduced14 SP/RSWE estimates.
% Plan: read-only file preflight. Run: reuse estimates, never reprocess IQ
% or refit either the quantile regressor or the risk classifier.
arguments
    options.Mode (1,1) string {mustBeMember(options.Mode,["plan","run"])} = "plan"
    options.DataRoot (1,1) string = ...
        "/Users/sara/local/experimental-data-reorganized/2026-02-27"
    options.ReqmlRoot (1,1) string = "/Users/sara/local/req-ml"
    options.EvalRoot (1,1) string = ...
        "/Users/sara/local/shear-wave-estimation-evaluation"
    options.QualityBundle (1,1) string = ""
    options.Experiments (1,:) string = ...
        ["2026Feb27_homo_5perc_sp","2026Feb27_homo_5perc_rswe"]
    options.Arms (1,:) string = ["reduced14","reduced14_filtered"]
    options.Frequencies (1,:) double = [300 400 500 600]
    options.M (1,1) double {mustBePositive} = 2
    options.MaximumRisks (1,:) double = [0.2 0.3]
    options.MakePlots (1,1) logical = true
    options.OutputName (1,1) string = "reduced14_quality_mask_transfer_v1"
end
assert(numel(unique(options.Experiments))==numel(options.Experiments) && ...
    ~isempty(options.Experiments) && ...
    all(endsWith(options.Experiments,"_sp") | ...
        endsWith(options.Experiments,"_rswe")), ...
    "QualityTransfer:Experiments","Use unique *_sp or *_rswe experiments.");
assert(~isempty(options.Arms) && ...
    numel(unique(options.Arms))==numel(options.Arms) && ...
    all(ismember(options.Arms,["reduced14","reduced14_filtered"])), ...
    "QualityTransfer:Arms","Only Reduced14 and Reduced14-filtered arms.");
assert(~isempty(options.Frequencies) && ...
    all(isfinite(options.Frequencies) & options.Frequencies>0) && ...
    numel(unique(options.Frequencies))==numel(options.Frequencies), ...
    "QualityTransfer:Frequencies","Frequencies must be unique and positive.");
assert(~isempty(options.MaximumRisks) && ...
    all(isfinite(options.MaximumRisks) & options.MaximumRisks>=0 & ...
    options.MaximumRisks<=1),"QualityTransfer:Thresholds", ...
    "Risk cutoffs must be in [0,1].");
qualityBundle=options.QualityBundle;
if qualityBundle==""
    qualityBundle=fullfile(options.ReqmlRoot,"training", ...
        "q0_v5_clean_campaign","outputs", ...
        "reduced14_quality_mask_v1","quality_mask_bundle.mat");
end
cases=struct("experiment",{},"arm",{},"frequency_hz",{}, ...
    "input_file",{},"output_file",{});
for experiment=options.Experiments
    if endsWith(experiment,"_rswe")
        kind="rswe";
    else
        kind="sp";
    end
    estimateName="reqml_"+kind+"_compare_m2_0p8_8_v1";
    root=fullfile(options.DataRoot,experiment);
    for arm=options.Arms
        for f=options.Frequencies
            item=struct("experiment",experiment,"arm",arm, ...
                "frequency_hz",f, ...
                "input_file",fullfile(root,"estimates",estimateName, ...
                    "REQ-ML",arm,sprintf("%gHz",f), ...
                    "M"+string(options.M),"reqml_result.mat"), ...
                "output_file",fullfile(root,"analysis", ...
                    options.OutputName,arm,sprintf("%gHz",f), ...
                    "M"+string(options.M),"risk_mask_result.mat"));
            cases(end+1)=item; %#ok<AGROW>
        end
    end
end
missing=strings(0,1);
if ~isfile(qualityBundle),missing(end+1)=qualityBundle;end
for j=1:numel(cases)
    if ~isfile(cases(j).input_file)
        missing(end+1)=cases(j).input_file; %#ok<AGROW>
    end
end
fprintf("Reduced14 experimental risk: %d estimates; %d missing inputs.\n", ...
    numel(cases),numel(missing));
if ~isempty(missing)
    disp(missing(1:min(12,numel(missing))))
end
out=struct("mode",options.Mode,"cases",cases, ...
    "missing_inputs",missing,"quality_bundle",qualityBundle, ...
    "summary",table());
if options.Mode=="plan"
    fprintf("Plan only: no outputs written.\n");
    return
end
assert(isempty(missing),"QualityTransfer:MissingInputs", ...
    "Missing %d required files; run Mode=plan to inspect paths.", ...
    numel(missing));
assert(isfolder(fullfile(options.EvalRoot,"src")) && ...
    isfolder(fullfile(options.ReqmlRoot,"training", ...
        "q0_v5_clean_campaign")),"QualityTransfer:RepoPaths", ...
    "REQ-ML and shear-wave-estimation-evaluation checkouts are required.");
addpath(fullfile(options.EvalRoot,"src"),"-begin");
addpath(fullfile(options.ReqmlRoot,"training", ...
    "q0_v5_clean_campaign"),"-begin");
assert(~isempty(which("q0v5.quality.predictRisk")) && ...
    ~isempty(which("swseval.qualitymask.analyzeResult")), ...
    "QualityTransfer:CodePath","Quality-mask functions not on MATLAB path.");
allSummary=cell(numel(cases),1);
for j=1:numel(cases)
    c=cases(j);
    inStamp=dir(c.input_file);bundleStamp=dir(qualityBundle);
    identity=struct("source_path",c.input_file, ...
        "source_bytes",double(inStamp.bytes), ...
        "source_date",double(inStamp.datenum), ...
        "bundle_path",qualityBundle, ...
        "bundle_bytes",double(bundleStamp.bytes), ...
        "bundle_date",double(bundleStamp.datenum), ...
        "arm",c.arm,"frequency_hz",c.frequency_hz, ...
        "max_risks",sort(unique(options.MaximumRisks(:)))');
    transfer_identity=string(jsonencode(identity)); %#ok<NASGU>
    figFile=fullfile(fileparts(c.output_file),"risk_and_sws_maps.png");
    if isfile(c.output_file)
        saved=load(c.output_file,"analysis","transfer_identity");
        assert(isfield(saved,"transfer_identity") && ...
            saved.transfer_identity==transfer_identity && ...
            isfield(saved,"analysis"),"QualityTransfer:Stale", ...
            "Existing result has different inputs/settings: %s",c.output_file);
        analysis=saved.analysis;
        fprintf("[%s %s %gHz] resumed\n", ...
            c.experiment,c.arm,c.frequency_hz);
    else
        s=load(c.input_file,"result");
        assert(isfield(s,"result"),"QualityTransfer:EstimateFormat", ...
            "Missing result variable in %s",c.input_file);
        analysis=swseval.qualitymask.analyzeResult(s.result,qualityBundle, ...
            MaximumRisks=options.MaximumRisks,Arm=c.arm);
        analysis.source_file=c.input_file;
        analysis.bundle_file=qualityBundle;
        analysis.experiment=c.experiment;
        analysis.frequency_hz=c.frequency_hz;
        folder=string(fileparts(c.output_file));
        if ~isfolder(folder),mkdir(folder);end
        partial=c.output_file+".partial.mat";
        assert(~isfile(partial),"QualityTransfer:Partial", ...
            "Inspect incomplete output before retrying: %s",partial);
        save(partial,"analysis","transfer_identity","-v7.3");
        assert(~isfile(c.output_file),"QualityTransfer:Race", ...
            "Output appeared during computation: %s",c.output_file);
        [ok,msg]=movefile(partial,c.output_file);
        assert(ok,"QualityTransfer:Write","Could not publish output: %s",msg);
        fprintf("[%s %s %gHz] risk transfer complete\n", ...
            c.experiment,c.arm,c.frequency_hz);
    end
    if options.MakePlots && ~isfile(figFile)
        swseval.qualitymask.plotMaps(analysis,figFile, ...
            Title=c.experiment+" | "+c.arm+" | "+ ...
                string(c.frequency_hz)+" Hz");
    end
    T=analysis.summary;
    T=addvars(T,repmat(c.experiment,height(T),1), ...
        repmat(c.arm,height(T),1), ...
        repmat(c.frequency_hz,height(T),1), ...
        "Before",1,"NewVariableNames", ...
        ["experiment","arm","frequency_hz"]);
    allSummary{j}=T;
end
out.summary=vertcat(allSummary{:});
fprintf("Completed %d transfer cases. Saved maps beside per-case MATs.\n", ...
    numel(cases));
end
