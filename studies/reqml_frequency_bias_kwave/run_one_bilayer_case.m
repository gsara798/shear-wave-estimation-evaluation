function out=run_one_bilayer_case(options)
%RUN_ONE_BILAYER_CASE One guarded 3D bilayer case with unchanged actuators.
% Without Execute=true, no files are written and no solver is invoked.
arguments
    options.CaseID (1,1) string = "bilayer_soft180_hard300_f500"
    options.SimulationRoot (1,1) string = ...
        "/Users/sara/local/shear-wave-simulation-framework"
    options.OutputRoot (1,1) string = ...
        "/Users/sara/local/experimental-data-reorganized/2026-02-27/_simulation_studies/reqml_frequency_bias_kwave_v1"
    options.GridSpacingM (1,1) double {mustBePositive} = 0.0005
    options.InterfaceZM (1,1) double {mustBeFinite} = 0
    options.Execute (1,1) logical = false
    options.ResourcesReviewed (1,1) logical = false
end
if options.Execute
    assert(options.ResourcesReviewed,"FreqBias:ResourceGate", ...
        "Check bilayer 3D RAM/runtime before setting ResourcesReviewed=true.");
end
T=prepare_bilayer_pilot( ...
    SimulationRoot=options.SimulationRoot,OutputRoot=options.OutputRoot, ...
    GridSpacingM=options.GridSpacingM,InterfaceZM=options.InterfaceZM, ...
    WriteConfigs=options.Execute);
row=find(T.case_id==options.CaseID);
assert(isscalar(row),"FreqBias:UnknownBilayerCase", ...
    "Unknown bilayer case: %s",options.CaseID);
out=struct("case_id",options.CaseID,"config_file",T.config_file(row), ...
    "run_file",T.run_file(row),"grid_spacing_m",options.GridSpacingM, ...
    "interface_z_m",options.InterfaceZM,"status","planned");
if ~options.Execute
    fprintf("Read-only bilayer preview. No solver executed.\n");
    return
end
cfg=jsondecode(fileread(T.config_file(row)));
assert(string(cfg.experiment)=="opposed_x_disks_bilayer_3d" && ...
    logical(cfg.bilayer.enabled) && ...
    abs(double(cfg.bilayer.interface_z_m)-options.InterfaceZM)<1e-12, ...
    "FreqBias:WrongBilayerConfig","Bilayer config mismatch.");
if T.completed(row)
    s=load(T.run_file(row),"result");
    assert(isfield(s,"result") && ...
        string(s.result.config.experiment)=="opposed_x_disks_bilayer_3d" && ...
        isfield(s.result.truth,"cs_m_s_zx") && ...
        isfield(s.result.truth,"material_id_zx") && ...
        double(s.result.config.frequency_hz)==T.frequency_hz(row) && ...
        abs(double(s.result.config.grid_spacing_m)-options.GridSpacingM)<1e-12 && ...
        abs(double(s.result.config.bilayer.interface_z_m)-options.InterfaceZM)<1e-12, ...
        "FreqBias:ExistingBilayerMismatch","Saved bilayer result identity differs.");
    out.status="skipped_verified_existing";
    return
end
runnerDir=fullfile(options.SimulationRoot, ...
    "examples","kwave","3d","opposed_x_disks");
assert(isfile(fullfile(runnerDir,"run_opposed_x_disks_3d.m")) && ...
    isfile(fullfile(runnerDir,"build_opposed_disk_material.m")), ...
    "FreqBias:BilayerRunnerMissing", ...
    "Update shear-wave-simulation-framework to the bilayer feature branch.");
addpath(fullfile(options.SimulationRoot,"src"));
addpath(runnerDir,"-begin");
assert(~isempty(which("build_opposed_disk_material")), ...
    "FreqBias:BilayerMaterialUnavailable","Bilayer material helper not on path.");
if isempty(which("pstdElastic3D"))
    kwavePath=string(getenv("KWSIM_KWAVE_PATH"));
    if strlength(kwavePath)>0 && isfolder(kwavePath)
        addpath(kwavePath);
        if isempty(which("pstdElastic3D")) && isfolder(fullfile(kwavePath,"k-Wave"))
            addpath(fullfile(kwavePath,"k-Wave"));
        end
    end
end
assert(~isempty(which("pstdElastic3D")),"FreqBias:KWaveUnavailable", ...
    "pstdElastic3D not found. Configure your k-Wave toolbox path.");
fprintf("Bilayer source runner: %s\n",which("run_opposed_x_disks_3d"));
outcome=run_opposed_x_disks_3d(T.config_file(row));
assert(isfile(outcome.run_file),"FreqBias:MissingBilayerOutput", ...
    "Solver returned without run.mat: %s",outcome.run_file);
s=load(outcome.run_file,"result");
assert(isfield(s.result.truth,"material_id_zx") && ...
    numel(unique(s.result.truth.material_id_zx))==2, ...
    "FreqBias:BilayerTruthMissing", ...
    "Result does not contain two labeled layers.");
out.run_file=string(outcome.run_file);
out.elapsed_s=outcome.elapsed_s;
out.status="completed";
fprintf("Bilayer case completed: %s\n",out.run_file);
end
