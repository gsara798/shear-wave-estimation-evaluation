function Q=qmv2_score_experimental_risk_mask(result,classifier,metadata,arm)
%QMV2_SCORE_EXPERIMENTAL_RISK_MASK Apply frozen QMV2 error-risk to exactly
% the SAME patch features, q predictions and grid as reqml.predictSWS.
% No new feature extraction, q prediction, truth, or cutoff tuning.
% NaN risk scores mark invalid/unscorable patches, NEVER safe regions.
arguments
    result (1,1) struct
    classifier
    metadata (1,1) struct
    arm (1,1) string
end
assert(all(isfield(result,cellstr(["patch_examples","q_map","cs_map", ...
    "valid_mask","x_mm","z_mm","metadata"]))), ...
    "ExpQMV2:MaskResult","REQ-ML result lacks full patch provenance.");
assert(all(isfield(metadata,cellstr(["schema","filter_arm", ...
    "quantile_predictor_set","predictor_names", ...
    "risk_probability_threshold","risk_error_threshold", ...
    "target_retention","test_used"]))), ...
    "ExpQMV2:MaskModel","Mask package lacks required provenance.");
assert(string(metadata.schema)=="qmv2_risk_mask_oof_v1" && ...
    ~logical(metadata.test_used) && ...
    isfinite(double(metadata.risk_probability_threshold)) && ...
    double(metadata.risk_probability_threshold)>=0 && ...
    double(metadata.risk_probability_threshold)<=1, ...
    "ExpQMV2:MaskProvenance", ...
    "Risk mask must be frozen, TRAIN-only, and have a finite OOF cutoff.");
expected="qmv2_"+string(metadata.filter_arm)+"_"+ ...
    string(metadata.quantile_predictor_set);
assert(arm==expected,"ExpQMV2:MaskArm", ...
    "Risk mask belongs to %s, but requested %s.",expected,arm);
assert(isfield(result.metadata,"model_provenance_id") && ...
    string(result.metadata.model_provenance_id)==arm, ...
    "ExpQMV2:MaskQuantileIdentity", ...
    "Saved SWS result was not produced by this frozen quantile model.");
baseValid=logical(result.valid_mask) & ...
    isfinite(double(result.cs_map)) & ...
    double(result.cs_map)>0 & isfinite(double(result.q_map));
assert(isequal(size(baseValid),size(result.q_map)), ...
    "ExpQMV2:MaskGrid","SWS and q maps have different dimensions.");
examples=result.patch_examples;
assert(istable(examples) && height(examples)>0 && ...
    all(ismember(["map_iz","map_ix"], ...
        string(examples.Properties.VariableNames))), ...
    "ExpQMV2:MaskPatchTable", ...
    "REQ-ML patch table requires map_iz and map_ix coordinates.");
iz=double(examples.map_iz(:));
ix=double(examples.map_ix(:));
shape=size(result.cs_map);
assert(all(isfinite(iz) & isfinite(ix)) && ...
    all(iz==round(iz) & ix==round(ix)) && ...
    all(iz>=1 & iz<=shape(1) & ix>=1 & ix<=shape(2)), ...
    "ExpQMV2:MaskPatchIndices", ...
    "Patch example map indices are invalid.");
linear=sub2ind(shape,iz,ix);
assert(numel(unique(linear))==numel(linear), ...
    "ExpQMV2:MaskDuplicatePatch","Duplicate patch map indices.");
names=string(metadata.predictor_names(:));
assert(~isempty(names) && ...
    names(end)=="qmv2_predicted_quantile" && ...
    numel(names)==numel(unique(names)), ...
    "ExpQMV2:MaskRegistry", ...
    "Frozen mask predictor list/order is invalid.");
X=nan(height(examples),numel(names));
for k=1:numel(names)
    feature=names(k);
    if feature=="qmv2_predicted_quantile"
        X(:,k)=double(result.q_map(linear));
    elseif feature=="frequency_hz"
        assert(isfield(result.metadata,"frequency_hz"), ...
            "ExpQMV2:MaskFrequency", ...
            "No frequency provided in experimental SWS metadata.");
        X(:,k)=double(result.metadata.frequency_hz);
    else
        assert(ismember(feature, ...
            string(examples.Properties.VariableNames)), ...
            "ExpQMV2:MaskPredictorMissing", ...
            "SWS patch features lack risk predictor %s.",feature);
        X(:,k)=double(examples.(char(feature)));
    end
end
frozenCutoff=double(metadata.risk_probability_threshold);
eligible=baseValid(linear) & all(isfinite(X),2);
score=nan(shape);
if any(eligible)
    [~,scores]=predict(classifier,X(eligible,:));
    riskClass=find(double(classifier.ClassNames(:))==1);
    assert(isscalar(riskClass),"ExpQMV2:MaskClass", ...
        "Mask classifier must have class 1 for SWS error risk.");
    values=double(scores(:,riskClass));
    assert(numel(values)==nnz(eligible) && ...
        all(isfinite(values) & values>=0 & values<=1), ...
        "ExpQMV2:MaskScore", ...
        "Risk scores must be finite in [0,1].");
    score(linear(eligible))=values;
end
validAndScored=baseValid & isfinite(score);
retained=validAndScored & score<=frozenCutoff;
rejected=validAndScored & score>frozenCutoff;
unscored=baseValid & ~validAndScored;
maskedSws=double(result.cs_map);
maskedSws(~retained)=NaN;
coverage=NaN;
if nnz(baseValid)>0
    coverage=nnz(retained)/nnz(baseValid);
end
Q=struct("risk_score_map",score, ...
    "retained_mask",retained, ...
    "rejected_mask",rejected, ...
    "unscored_mask",unscored, ...
    "original_valid_mask",baseValid, ...
    "masked_sws_map",maskedSws, ...
    "x_mm",double(result.x_mm), ...
    "z_mm",double(result.z_mm), ...
    "original_sws_map",double(result.cs_map), ...
    "q_map",double(result.q_map), ...
    "cutoff",frozenCutoff, ...
    "coverage_on_original_valid",coverage, ...
    "original_valid_count",nnz(baseValid), ...
    "retained_count",nnz(retained), ...
    "rejected_count",nnz(rejected), ...
    "unscored_count",nnz(unscored), ...
    "quantile_arm",arm, ...
    "mask_metadata",metadata);
assert(nnz(retained)+nnz(rejected)+nnz(unscored)==nnz(baseValid), ...
    "ExpQMV2:MaskPartition", ...
    "Retained, rejected and unscored SWS windows must partition valid SWS.");
end
