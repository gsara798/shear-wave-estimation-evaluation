function C=read_qmv2_experiment_manifest(file)
%READ_QMV2_EXPERIMENT_MANIFEST Validate experimental study inputs.
% Physical paths, datasets, frequency lists, ROI definitions, processing
% names and model selections live in JSON, never in MATLAB source code.
arguments
    file (1,1) string
end
assert(isfile(file),"ExpQMV2:ManifestMissing", ...
    "Manifest JSON does not exist: %s",file);
C=jsondecode(fileread(file));
required=["study_id","data_root","reqml_root","cases","arms", ...
    "filtered_run","filter"];
assert(all(isfield(C,cellstr(required))), ...
    "ExpQMV2:ManifestSchema", ...
    "Missing manifest keys: %s",strjoin(required(~isfield(C,cellstr(required))),", "));
assert(isstruct(C.cases) && ~isempty(C.cases), ...
    "ExpQMV2:EmptyCases","Manifest needs one or more cases.");
C.study_id=string(C.study_id);
C.data_root=string(C.data_root);
C.reqml_root=string(C.reqml_root);
C.filtered_run=string(C.filtered_run);
C.arms=string(C.arms(:))';
assert(strlength(C.study_id)>0 && all(isstrprop(char(C.study_id),"alphanum") | ...
    ismember(char(C.study_id),['_','-'])), ...
    "ExpQMV2:StudyID","Study identifier must be a safe directory component.");
assert(strlength(C.data_root)>0 && strlength(C.reqml_root)>0, ...
    "ExpQMV2:Roots","Configure data_root and reqml_root in the manifest.");
assert(~isempty(C.arms) && numel(unique(C.arms))==numel(C.arms), ...
    "ExpQMV2:Arms","Arms must be nonempty and unique.");
% isfield accepts a cell array of *char vectors*, not cells of MATLAB
% string scalars. Using {"a","b"} here causes a false-negative schema
% check on supported MATLAB versions (all four tests fail immediately).
filterNames=["cs_min_m_s","cs_max_m_s","taper_relative"];
assert(isstruct(C.filter) && isscalar(C.filter), ...
    "ExpQMV2:Filter","Filter must be one JSON object.");
assert(all(isfield(C.filter,cellstr(filterNames))), ...
    "ExpQMV2:Filter", ...
    "Filter is missing fields: %s", ...
    strjoin(filterNames(~isfield(C.filter,cellstr(filterNames))),", "));
filterValues=[C.filter.cs_min_m_s,C.filter.cs_max_m_s, ...
    C.filter.taper_relative];
assert(isnumeric(filterValues) && numel(filterValues)==3 && ...
    all(isfinite(filterValues)) && filterValues(1)>0 && ...
    filterValues(2)>filterValues(1) && ...
    filterValues(3)>=0 && filterValues(3)<1, ...
    "ExpQMV2:Filter", ...
    "Filter must have 0 < cs_min_m_s < cs_max_m_s and 0 <= taper_relative < 1.");
if ~isfield(C,"m"),C.m=2;end
C.m=double(C.m);
if ~isfield(C,"step_pixels"),C.step_pixels=5;end
C.step_pixels=double(C.step_pixels);
if ~isfield(C,"sws_limits"),C.sws_limits=[1 4];end
C.sws_limits=double(C.sws_limits(:))';
if ~isfield(C,"analysis_version"),C.analysis_version="roi_draft_v1";end
C.analysis_version=string(C.analysis_version);
assert(isscalar(C.m) && C.m>0 && ...
    isscalar(C.step_pixels) && C.step_pixels>=1 && ...
    C.step_pixels==round(C.step_pixels) && ...
    numel(C.sws_limits)==2 && all(isfinite(C.sws_limits)) && ...
    C.sws_limits(2)>C.sws_limits(1) && ...
    strlength(C.analysis_version)>0 && ...
    all(isstrprop(char(C.analysis_version),"alphanum") | ...
    ismember(char(C.analysis_version),['_','-'])), ...
    "ExpQMV2:NumericConfig","Invalid M, step, SWS limits or analysis version.");
assert(strlength(C.filtered_run)>0 && ...
    ~any(contains(C.filtered_run,["/","\"])) && ...
    ~contains(C.filtered_run,".."), ...
    "ExpQMV2:FilteredRun","Choose a safe, unique derived filtered-run name.");
names=strings(numel(C.cases),1);
for i=1:numel(C.cases)
    caseSpec=C.cases(i);
    need=["id","relative_path","modality","type","raw_run", ...
        "raw_file_pattern","frequencies_hz"];
    assert(all(isfield(caseSpec,cellstr(need))), ...
        "ExpQMV2:CaseSchema", ...
        "Each case needs id, relative_path, modality, type, raw_run, raw_file_pattern, frequencies_hz.");
    names(i)=string(caseSpec.id);
    rel=string(caseSpec.relative_path);
    assert(strlength(names(i))>0 && ...
        ~any(contains(names(i),["/","\","."])) && ...
        strlength(rel)>0 && ...
        ~any(startsWith(rel,["/","\","."])) && ...
        ~contains(rel,"..") && ...
        ismember(string(caseSpec.modality),["sp","rswe"]) && ...
        ismember(string(caseSpec.type),["homogeneous","bilayer","inclusion"]), ...
        "ExpQMV2:CaseIdentity", ...
        "Unsafe path, ID, modality or phantom type in case %d.",i);
    f=double(caseSpec.frequencies_hz(:));
    assert(all(isfinite(f) & f>0 & round(f)==f) && ...
        numel(f)==numel(unique(f)), ...
        "ExpQMV2:Frequencies","Frequency list must contain unique positive integers.");
    rawRun=string(caseSpec.raw_run);
    assert(isscalar(rawRun) && ...
        ~any(contains(rawRun,["/","\"])) && ~contains(rawRun,".."), ...
        "ExpQMV2:RawRun","Invalid processing run in case %s.",names(i));
    if ~isfield(caseSpec,"rois") || isempty(caseSpec.rois)
        continue
    end
    rois=caseSpec.rois;
    assert(isstruct(rois),"ExpQMV2:ROISchema", ...
        "ROIs must be a list of physical-geometry objects.");
    roiNames=strings(numel(rois),1);
    for j=1:numel(rois)
        roi=rois(j);
        assert(all(isfield(roi,cellstr(["name","center_mm","size_mm"]))) && ...
            numel(roi.center_mm)==2 && numel(roi.size_mm)==2 && ...
            all(isfinite(double(roi.center_mm(:)))) && ...
            all(isfinite(double(roi.size_mm(:)))) && ...
            all(double(roi.size_mm(:))>0), ...
            "ExpQMV2:ROI", ...
            "ROI %d of %s needs name, center_mm and positive size_mm.",j,names(i));
        roiNames(j)=string(roi.name);
        assert(~isfield(roi,"shape") || string(roi.shape)=="rectangle", ...
            "ExpQMV2:ROIShape", ...
            "Current evaluation only supports rectangular ROIs; do not guess inclusion geometry.");
    end
    assert(numel(unique(roiNames))==numel(roiNames) && ...
        all(strlength(roiNames)>0), ...
        "ExpQMV2:ROIDuplicates","ROI names must be nonempty and distinct.");
end
assert(numel(unique(names))==numel(names), ...
    "ExpQMV2:DuplicateCases","Each dataset ID must be unique.");
end
