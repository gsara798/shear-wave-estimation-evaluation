function C=qmv2_inclusion_contrasts(T,contrasts)
%QMV2_INCLUSION_CONTRASTS Paired ROI descriptors from SWS observations.
% Contrast pairs are named in the JSON manifest, not hard-coded here.
% Relative contrast: 100 * (median_target/median_background - 1).
% Descriptive spatial CNR: (mean_target-mean_background) /
% sqrt(sd_target^2 + sd_background^2), not a statistical significance test.
% No independent stiffness truth is inferred from phantom designation.
arguments
    T table
    contrasts struct
end
assert(all(ismember(["case_id","modality","phantom_type","frequency_hz", ...
    "model","roi","mean_sws_m_s","median_sws_m_s","spatial_sd_m_s", ...
    "common_valid_pixels","roi_extent_in_sample_fraction"], ...
    string(T.Properties.VariableNames))), ...
    "ExpQMV2:ContrastColumns","ROI summary missing required columns.");
assert(~isempty(contrasts),"ExpQMV2:ContrastEmpty", ...
    "Contrast rules must be supplied from the experimental manifest.");
rows=cell(0,1);
cases=unique(string(T.case_id),"stable");
assert(numel(cases)==1,"ExpQMV2:ContrastCase", ...
    "Contrast helper expects exactly one physical dataset.");
for ri=1:numel(contrasts)
    rule=contrasts(ri);
    label=string(rule.name);
    aName=string(rule.target_roi);
    bName=string(rule.reference_roi);
    models=unique(string(T.model),"stable");
    frequencies=unique(double(T.frequency_hz),"stable");
    for model=models'
        for f=frequencies'
            a=T(string(T.model)==model & double(T.frequency_hz)==f & ...
                string(T.roi)==aName,:);
            b=T(string(T.model)==model & double(T.frequency_hz)==f & ...
                string(T.roi)==bName,:);
            assert(height(a)==1 && height(b)==1, ...
                "ExpQMV2:ContrastPair", ...
                "Expected 1 target and 1 reference ROI for %s, %g Hz, %s.", ...
                model,f,label);
            targetN=double(a.common_valid_pixels);
            backgroundN=double(b.common_valid_pixels);
            meanDiff=NaN;medianDiff=NaN;ratio=NaN; ...
                contrastPercent=NaN;cnr=NaN;
            if targetN>0 && backgroundN>0 && ...
                    isfinite(double(a.median_sws_m_s)) && ...
                    isfinite(double(b.median_sws_m_s))
                medianDiff=double(a.median_sws_m_s)- ...
                    double(b.median_sws_m_s);
                if double(b.median_sws_m_s)>0
                    ratio=double(a.median_sws_m_s)/ ...
                        double(b.median_sws_m_s);
                    contrastPercent=100*(ratio-1);
                end
                meanDiff=double(a.mean_sws_m_s)-double(b.mean_sws_m_s);
                denom=hypot(double(a.spatial_sd_m_s), ...
                    double(b.spatial_sd_m_s));
                if isfinite(denom) && denom>0 && ...
                        isfinite(meanDiff)
                    cnr=meanDiff/denom;
                end
            end
            rows{end+1,1}=table( ...
                string(a.case_id),string(a.modality), ...
                f,model,label,aName,bName, ...
                targetN,backgroundN, ...
                double(a.roi_extent_in_sample_fraction), ...
                double(b.roi_extent_in_sample_fraction), ...
                double(a.median_sws_m_s), ...
                double(b.median_sws_m_s), ...
                double(a.mean_sws_m_s), ...
                double(b.mean_sws_m_s), ...
                medianDiff,meanDiff,ratio,contrastPercent,cnr, ...
                'VariableNames',["case_id","modality","frequency_hz", ...
                "model","contrast_name","target_roi","reference_roi", ...
                "target_common_pixels","reference_common_pixels", ...
                "target_roi_fov_fraction", ...
                "reference_roi_fov_fraction", ...
                "target_median_sws_m_s", ...
                "reference_median_sws_m_s", ...
                "target_mean_sws_m_s", ...
                "reference_mean_sws_m_s", ...
                "median_sws_difference_m_s", ...
                "mean_sws_difference_m_s", ...
                "median_sws_ratio", ...
                "median_contrast_percent","spatial_cnr"]); %#ok<AGROW>
        end
    end
end
C=vertcat(rows{:});
end
