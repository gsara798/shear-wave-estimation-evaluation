function files=qmv2_plot_experimental_mask_rois(C,jobs,models,version)
%QMV2_PLOT_EXPERIMENTAL_MASK_ROIS Plot already analyzed mask statistics.
% One figure per physical ROI: coverage, CV, and median SWS before/after.
% Plus inclusion contrast vs frequency and inclusion/background coverage.
% No estimation, classification, re-thresholding, refit, or map replay.
arguments
    C (1,1) struct
    jobs table
    models table
    version (1,1) string
end
summaryRoot=fullfile(C.data_root,"analysis",C.study_id, ...
    "M"+string(C.m)+"_step"+string(C.step_pixels),version);
summaryFile=fullfile(summaryRoot,"quality_mask_experimental_roi_summary.csv");
assert(isfile(summaryFile),"ExpQMV2:MaskROIPlotsNeedAnalyze", ...
    "Run Mode=analyze first: %s",summaryFile);
T=readtable(summaryFile,TextType="string", ...
    VariableNamingRule="preserve");
required=["case_id","frequency_hz","arm","roi", ...
    "retained_fraction","median_sws_before","median_sws_after", ...
    "cv_percent_before","cv_percent_after"];
assert(all(ismember(required,string(T.Properties.VariableNames))), ...
    "ExpQMV2:MaskROIPlotColumns", ...
    "Saved quality-mask ROI summary lacks required columns.");
cases=unique(string(jobs.case_id),"stable");
arms=string(models.arm(:))';
assert(isequal(sort(unique(string(T.arm))),sort(arms(:))) && ...
    isequal(sort(unique(string(T.case_id))),sort(cases(:))), ...
    "ExpQMV2:MaskROIPlotScope", ...
    "Saved ROI analysis has a different case/model selection.");
colors=lines(numel(arms));
labels=shortNames(arms);
files=strings(0,1);
for id=cases'
    thisCase=jobs(jobs.case_id==id,:);
    frequencies=sort(unique(double(thisCase.frequency_hz)));
    subset=T(string(T.case_id)==id,:);
    assert(isequal(sort(unique(double(subset.frequency_hz))),frequencies), ...
        "ExpQMV2:MaskROIPlotFrequency", ...
        "ROI summary frequencies do not match selected jobs: %s.",id);
    output=fullfile(thisCase.dataset_root(1),"analysis", ...
        C.study_id,"M"+string(C.m)+"_step"+ ...
        string(C.step_pixels),version,"roi_figures");
    if ~isfolder(output),mkdir(output);end
    roiNames=unique(string(subset.roi),"stable");
    for roi=roiNames'
        dat=subset(string(subset.roi)==roi,:);
        fig=figure("Visible","off","Color","w", ...
            "Position",[50 50 1650 565]);
        tl=tiledlayout(fig,1,3,"TileSpacing","compact", ...
            "Padding","compact");
        ax=nexttile(tl);hold(ax,"on");
        bx=nexttile(tl);hold(bx,"on");
        cx=nexttile(tl);hold(cx,"on");
        handles=gobjects(1,numel(arms));
        for ai=1:numel(arms)
            arm=arms(ai);
            U=sortrows(dat(string(dat.arm)==arm,:),"frequency_hz");
            assert(height(U)==numel(frequencies) && ...
                isequal(double(U.frequency_hz(:)),frequencies(:)), ...
                "ExpQMV2:MaskROIPlotRows", ...
                "Expected one frequency row per arm/ROI: %s / %s / %s.", ...
                id,arm,roi);
            x=double(U.frequency_hz);
            handles(ai)=plot(ax,x,100*double(U.retained_fraction), ...
                "-o","Color",colors(ai,:),"LineWidth",1.7, ...
                "MarkerSize",5);
            plot(bx,x,double(U.cv_percent_before),"-o", ...
                "Color",colors(ai,:),"LineWidth",1.35, ...
                "MarkerSize",4,"HandleVisibility","off");
            plot(bx,x,double(U.cv_percent_after),"--s", ...
                "Color",colors(ai,:),"LineWidth",1.35, ...
                "MarkerSize",4,"HandleVisibility","off");
            plot(cx,x,double(U.median_sws_before),"-o", ...
                "Color",colors(ai,:),"LineWidth",1.35, ...
                "MarkerSize",4,"HandleVisibility","off");
            plot(cx,x,double(U.median_sws_after),"--s", ...
                "Color",colors(ai,:),"LineWidth",1.35, ...
                "MarkerSize",4,"HandleVisibility","off");
        end
        ylim(ax,[0,105]);
        title(ax,"Physical ROI coverage");
        ylabel(ax,"Retained original-valid pixels (%)");
        title(bx,"Spatial variability (solid before, dashed after)");
        ylabel(bx,"CV (%)");
        title(cx,"Shear-wave speed (solid before, dashed after)");
        ylabel(cx,"Median SWS (m/s)");
        for a=[ax bx cx]
            xlabel(a,"Frequency (Hz)");
            xticks(a,frequencies');
            grid(a,"on");box(a,"on");
        end
        lg=legend(ax,handles,cellstr(labels),"Interpreter","none", ...
            "Box","off","NumColumns",numel(arms));
        lg.Layout.Tile="south";
        title(tl,id+" | ROI: "+roi+" | frozen 80% TRAIN cutoff", ...
            "Interpreter","none");
        filename=fullfile(output,"mask_roi_"+roi+".png");
        exportgraphics(fig,filename,Resolution=175);
        close(fig);
        files(end+1,1)=filename; %#ok<AGROW>
    end
end
contrastFile=fullfile(summaryRoot,"quality_mask_inclusion_contrasts.csv");
if isfile(contrastFile)
    Ctab=readtable(contrastFile,TextType="string", ...
        VariableNamingRule="preserve");
    assert(all(ismember(["case_id","frequency_hz","arm", ...
        "contrast_name","target_retained_fraction", ...
        "background_retained_fraction","contrast_before_percent", ...
        "contrast_after_percent"], ...
        string(Ctab.Properties.VariableNames))), ...
        "ExpQMV2:MaskROIPlotContrast", ...
        "Saved inclusion contrast table lacks required columns.");
    for id=cases'
        subset=Ctab(string(Ctab.case_id)==id,:);
        if isempty(subset),continue,end
        caseIndex=find(string({C.cases.id})==id);
        assert(isscalar(caseIndex),"ExpQMV2:MaskROIPlotCase", ...
            "Expected exactly one physical case for %s.",id);
        output=fullfile(C.data_root, ...
            string(C.cases(caseIndex).relative_path), ...
            "analysis",C.study_id,"M"+string(C.m)+"_step"+ ...
            string(C.step_pixels),version,"roi_figures");
        contrastNames=unique(string(subset.contrast_name),"stable");
        for contrast=contrastNames'
            dat=subset(string(subset.contrast_name)==contrast,:);
            fig=figure("Visible","off","Color","w", ...
                "Position",[50 50 1250 570]);
            tl=tiledlayout(fig,1,2, ...
                "TileSpacing","compact","Padding","compact");
            ax=nexttile(tl);hold(ax,"on");
            bx=nexttile(tl);hold(bx,"on");
            handles=gobjects(1,numel(arms));
            for ai=1:numel(arms)
                U=sortrows(dat(string(dat.arm)==arms(ai),:), ...
                    "frequency_hz");
                if isempty(U),continue,end
                x=double(U.frequency_hz);
                handles(ai)=plot(ax,x,double(U.contrast_before_percent), ...
                    "-o","Color",colors(ai,:), ...
                    "LineWidth",1.35,"MarkerSize",4);
                plot(ax,x,double(U.contrast_after_percent),"--s", ...
                    "Color",colors(ai,:), ...
                    "LineWidth",1.35,"MarkerSize",4, ...
                    "HandleVisibility","off");
                plot(bx,x,100*double(U.target_retained_fraction), ...
                    "-o","Color",colors(ai,:), ...
                    "LineWidth",1.35,"MarkerSize",4, ...
                    "HandleVisibility","off");
                plot(bx,x,100*double(U.background_retained_fraction), ...
                    "--s","Color",colors(ai,:), ...
                    "LineWidth",1.35,"MarkerSize",4, ...
                    "HandleVisibility","off");
            end
            title(ax,"Median contrast: solid before, dashed after");
            ylabel(ax,"Inclusion / background contrast (%)");
            title(bx,"Coverage: solid inclusion, dashed background");
            ylabel(bx,"Retained original-valid pixels (%)");
            ylim(bx,[0 105]);
            for a=[ax bx]
                xlabel(a,"Frequency (Hz)");
                xticks(a,sort(unique(double(dat.frequency_hz)))');
                grid(a,"on");box(a,"on");
            end
            lg=legend(ax,handles,cellstr(labels), ...
                "Interpreter","none","Box","off", ...
                "NumColumns",numel(arms));
            lg.Layout.Tile="south";
            title(tl,id+" | "+contrast+ ...
                " | NaN = insufficient retained pixels", ...
                "Interpreter","none");
            filename=fullfile(output,"mask_contrast_"+contrast+".png");
            exportgraphics(fig,filename,Resolution=175);
            close(fig);
            files(end+1,1)=filename; %#ok<AGROW>
        end
    end
end
fprintf("QMV2 experimental ROI plots: %d figures created.\n",numel(files));
end

function names=shortNames(arms)
names=arms;
names=replace(names,"qmv2_unfiltered_reduced14","R14 raw");
names=replace(names,"qmv2_unfiltered_expanded20","E20 raw");
names=replace(names,"qmv2_fixed_donut_reduced14","R14 donut");
names=replace(names,"qmv2_fixed_donut_expanded20","E20 donut");
end
