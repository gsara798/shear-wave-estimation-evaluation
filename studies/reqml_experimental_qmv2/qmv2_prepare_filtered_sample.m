function status=qmv2_prepare_filtered_sample(source,dest,filter)
%QMV2_PREPARE_FILTERED_SAMPLE Apply the canonical global FFT donut once.
% Never modifies the EWP/raw observation. Resume requires matching source
% size/mtime, filter settings and a separate manifest. No silent overwrite.
arguments
    source (1,1) string
    dest (1,1) string
    filter (1,1) struct
end
assert(isfile(source),"ExpQMV2:RawMissing", ...
    "Missing processed EWP raw sample: %s",source);
assert(source~=dest,"ExpQMV2:OverwriteRaw", ...
    "Raw and filtered output paths must be distinct.");
stamp=dir(source);
identity=struct("source",source,"source_bytes",double(stamp.bytes), ...
    "source_datenum",double(stamp.datenum), ...
    "filter_type","global_complex_fft_donut", ...
    "cs_min_m_s",double(filter.cs_min_m_s), ...
    "cs_max_m_s",double(filter.cs_max_m_s), ...
    "taper_relative",double(filter.taper_relative));
signature=string(jsonencode(identity));
folder=string(fileparts(dest));
manifest=fullfile(folder,"filter_manifest.mat");
if isfile(dest) || isfile(manifest)
    assert(isfile(dest) && isfile(manifest), ...
        "ExpQMV2:FilterPartial", ...
        "Filtered output and manifest must both exist: %s",folder);
    previous=load(manifest,"signature");
    assert(isfield(previous,"signature") && ...
        string(previous.signature)==signature, ...
        "ExpQMV2:FilterStale", ...
        "Prior filtered field differs in source/settings: %s",dest);
    status="reused";
    return
end
S=load(source,"wavefield_sample");
assert(isfield(S,"wavefield_sample"), ...
    "ExpQMV2:WavefieldSchema","Missing wavefield_sample: %s",source);
wavefield_sample=S.wavefield_sample; %#ok<NASGU>
assert(isfield(wavefield_sample,"coordinates") && ...
    isfield(wavefield_sample,"wavefield") && ...
    isfield(wavefield_sample.wavefield,"data_zx") && ...
    isfield(wavefield_sample.wavefield,"frequency_hz"), ...
    "ExpQMV2:WavefieldSchema", ...
    "Unexpected EWP sample schema: %s",source);
if ~isfield(wavefield_sample,"provenance")
    wavefield_sample.provenance=struct();
end
assert(~isfield(wavefield_sample.provenance,"qmv2_filter") && ...
    ~isfield(wavefield_sample.provenance,"comparison_filter_v1"), ...
    "ExpQMV2:DoubleFilter","Input is already tagged as filtered.");
response=q0v5.filter.applyFixedDonut( ...
    wavefield_sample.wavefield.data_zx, ...
    double(wavefield_sample.coordinates.dx_m), ...
    double(wavefield_sample.coordinates.dz_m), ...
    double(wavefield_sample.wavefield.frequency_hz), ...
    CsMinMS=double(filter.cs_min_m_s), ...
    CsMaxMS=double(filter.cs_max_m_s), ...
    TaperRelative=double(filter.taper_relative));
wavefield_sample.wavefield.data_zx=response.field_zx;
wavefield_sample.provenance.qmv2_filter=identity;
if ~isfolder(folder),mkdir(folder);end
partial=dest+".partial.mat";
assert(~isfile(partial),"ExpQMV2:FilterPartial", ...
    "Inspect incomplete output: %s",partial);
save(partial,"wavefield_sample","-v7.3");
[ok,msg]=movefile(partial,dest);
assert(ok,"ExpQMV2:FilterWrite","%s",msg);
retained_power_fraction=response.retained_energy_fraction; %#ok<NASGU>
save(manifest,"signature","identity","retained_power_fraction");
status="created";
end
