function out=run_estimation(varargin)
%RUN_ESTIMATION Run/resume 5 frozen Q0 models over processed SP wavefields.
% Usage: run_estimation(); does NOT reprocess IQ or fit a new model.
c=sp_comparison_config(varargin{:});
estimateAll(c,c);
out=struct("stage","estimate","experiments",c.Experiments, ...
    "arms",c.arms,"comparison_name",c.comparisonName);
end

function estimateAll(o,c)
assert(~isempty(which("reqml.predictSWS")), ...
    "SPCompare:REQML","reqml.predictSWS not available.");
assert(~isempty(which("reqml.models.loadQ0Model")), ...
    "SPCompare:REQML","Model loader not available.");
% Deployment-compatible v2 bundle, generated from the EXISTING fitted model.
% This does NOT retrain. Refuses to replace any existing inconsistent bundle.
makeFilteredV2Bundle(c.v2Checkpoint,c.v2Bundle,o.ReqmlRoot);
modelFiles=[resolveBundle(c.v1);resolveBundle(c.v1); ...
    resolveBundle(c.v2Bundle);resolveBundle(c.candidate10); ...
    resolveBundle(c.candidate)];
for ai=1:numel(c.arms)
    loaded=reqml.models.loadQ0Model(Model=modelFiles(ai));
    fprintf("\nMODEL %s: %d features\n",c.arms(ai), ...
        numel(loaded.predictor_names));
    for experiment=o.Experiments
        root=fullfile(o.DataRoot,experiment);
        estimatesRoot=fullfile(root,"estimates",c.comparisonName);
        outputRoot=fullfile(estimatesRoot,"REQ-ML",c.arms(ai));
        if c.inputKinds(ai)=="filtered"
            processedRun=c.filteredRun;
        else
            processedRun=c.rawRun;
        end
        for f=o.Frequencies
            sample=sampleFile(root,processedRun,f);
            assert(isfile(sample),"SPCompare:ProcessFirst", ...
                "Missing processed wavefield %s (run Stage=process).",sample);
            dest=fullfile(outputRoot,sprintf("%gHz",f), ...
                "M"+string(o.M),"reqml_result.mat");
            savedir=string(fileparts(dest));
            if ~isfolder(savedir),mkdir(savedir);end
            srcStamp=dir(sample);modStamp=dir(modelFiles(ai));
            record=struct("arm",c.arms(ai),"sample",sample, ...
                "sample_bytes",double(srcStamp.bytes), ...
                "sample_date",double(srcStamp.datenum), ...
                "model_file",modelFiles(ai), ...
                "model_bytes",double(modStamp.bytes), ...
                "model_date",double(modStamp.datenum), ...
                "M",o.M,"step_pixels",o.StepPixels);
            comparison_identity=string(jsonencode(record)); %#ok<NASGU>
            if isfile(dest)
                assert(o.Resume,"SPCompare:ResultExists", ...
                    "Existing estimate must not be overwritten: %s",dest);
                saved=load(dest,"comparison_identity");
                assert(isfield(saved,"comparison_identity") && ...
                    string(saved.comparison_identity)==comparison_identity, ...
                    "SPCompare:ResultStale", ...
                    "An existing result has different model/input/settings: %s",dest);
                fprintf("[%s/%s/%gHz] resumed\n",experiment,c.arms(ai),f);
                continue
            end
            fprintf("[%s/%s/%gHz] predicting M=%g...\n", ...
                experiment,c.arms(ai),f,o.M);
            % reqml.predictSWS uses valid-only patches by default.
            % Direct call avoids dependency on a separate sweep branch.
            result=reqml.predictSWS(sample,ModelBundle=loaded, ...
                M=o.M,StepPixels=o.StepPixels, ...
                UseParallel=o.UseParallel,Verbose=false); %#ok<NASGU>
            result.metadata.comparison_arm=c.arms(ai);
            result.metadata.comparison_processing=processedRun;
            result.metadata.comparison_step_pixels=o.StepPixels;
            tmp=dest+".partial.mat";
            assert(~isfile(tmp),"SPCompare:Partial", ...
                "Inspect partial result first: %s",tmp);
            save(tmp,"result","comparison_identity","-v7.3");
            [ok,msg]=movefile(tmp,dest);
            assert(ok,"SPCompare:EstimateWrite", ...
                "Could not publish estimate: %s",msg);
        end
    end
end
end

function dest=sampleFile(root,runName,f)
dest=fullfile(root,"processed",runName, ...
    sprintf("%gHz",f),"wavefield_sample.mat");
end

function file=resolveBundle(path)
path=string(path);
if isfile(path)
    file=path;return
end
if ~isfolder(path)
    error("SPCompare:ModelMissing", ...
        "Model not found: %s",path);
end
candidate=fullfile(path,"model_bundle.mat");
if isfile(candidate)
    file=candidate;return
end
% Some older runs save their bundle one directory below the model folder.
% Accept a unique bundle only; never guess among multiple candidates.
d=dir(fullfile(path,"**","model_bundle.mat"));
if numel(d)==1
    file=fullfile(string(d(1).folder),string(d(1).name));
    return
end
if numel(d)>1
    error("SPCompare:AmbiguousModelBundle", ...
        "Found %d candidate model bundles under %s; select one explicitly.", ...
        numel(d),path);
end
error("SPCompare:ModelBundleMissing", ...
    "No model_bundle.mat in %s. Publish this candidate as a REQ-ML bundle.",path);
end

function makeFilteredV2Bundle(checkpoint,bundleFile,repoRoot)
assert(isfile(checkpoint),"SPCompare:FilteredV2Missing", ...
    "Filtered-v2 fitted model checkpoint not found: %s",checkpoint);
s=load(checkpoint,"model","predictors","signature","train_geometry_ids");
assert(isfield(s,"model") && isfield(s,"predictors") && ...
    isfield(s,"signature") && isfield(s,"train_geometry_ids"), ...
    "SPCompare:FilteredV2Format", ...
    "Expected fitted filtered v2 checkpoint with model, predictors and train IDs.");
expected=q0v5.extraction.reducedModelSets();
names=string(expected(2).predictor_names(:));
assert(isequal(string(s.predictors(:)),names) && ...
    numel(unique(string(s.train_geometry_ids(:))))==210 && ...
    string(s.model.model_type)=="bagged_trees" && ...
    double(s.model.num_learning_cycles)==160 && ...
    double(s.model.min_leaf_size)==2 && ...
    numel(s.model.mu)==16, ...
    "SPCompare:FilteredV2Identity","Wrong v2 model/checkpoint configuration.");
source=dir(checkpoint);
model_id="reqml_q0_v5_localonly_reduced16_filtered_v2";
if isfile(bundleFile)
    z=load(bundleFile,"model_metadata","predictor_names");
    assert(isfield(z,"model_metadata") && ...
        isfield(z,"predictor_names") && ...
        isequal(string(z.predictor_names(:)),names) && ...
        isfield(z.model_metadata,"source_signature") && ...
        string(z.model_metadata.source_signature)==string(s.signature) && ...
        string(z.model_metadata.model_id)==model_id && ...
        double(z.model_metadata.source_bytes)==double(source.bytes) && ...
        double(z.model_metadata.source_datenum)==double(source.datenum), ...
        "SPCompare:FilteredV2BundleMismatch", ...
        "Existing filtered-v2 deployment bundle differs from checkpoint.");
    return
end
model=s.model; %#ok<NASGU>
predictor_names=names; %#ok<NASGU>
model_metadata=struct("model_id",model_id, ...
    "source_checkpoint",checkpoint, ...
    "source_signature",string(s.signature), ...
    "source_bytes",double(source.bytes), ...
    "source_datenum",double(source.datenum), ...
    "predictor_names",names, ...
    "training_scope","train_only", ...
    "training_geometry_count",210, ...
    "filter",struct("CsMinMS",0.8,"CsMaxMS",8, ...
        "TaperRelative",0.06, ...
        "application","global_complex_wavefield_before_REQ"), ...
    "source_repo_root",repoRoot); %#ok<NASGU>
folder=string(fileparts(bundleFile));
if ~isfolder(folder),mkdir(folder);end
tmp=bundleFile+".partial.mat";
assert(~isfile(tmp),"SPCompare:Partial", ...
    "Inspect partial bundle first: %s",tmp);
save(tmp,"model","predictor_names","model_metadata","-v7.3");
% Verify roundtrip predictions, not only number/order of predictors.
check=load(tmp,"model","predictor_names");
probe=[double(model.mu); double(model.mu)+double(model.sigma)];
ref=reqml.models.predictRegressionModel(model,probe);
q=reqml.models.predictRegressionModel(check.model,probe);
assert(isequal(string(check.predictor_names(:)),names) && ...
    max(abs(ref-q))<1e-12,"SPCompare:FilteredV2Roundtrip", ...
    "Bundle predictions changed during save/load.");
[ok,msg]=movefile(tmp,bundleFile);
assert(ok,"SPCompare:FilteredV2Write", ...
    "Cannot publish filtered-v2 model bundle: %s",msg);
reqml.models.loadQ0Model(Model=bundleFile);
fprintf("Packaged existing filtered-v2 model: %s\n",bundleFile);
end
