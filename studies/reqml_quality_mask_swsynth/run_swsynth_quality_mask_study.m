function out=run_swsynth_quality_mask_study(options)
%RUN_SWSYNTH_QUALITY_MASK_STUDY Test frozen v1 risk against synthetic truth.
% Reuses 20 existing swsynth fields and saved Reduced14 estimates; it does
% not simulate, estimate, filter or train. Non-default cases are a pilot.
arguments
    options.Mode (1,1) string {mustBeMember(options.Mode,["plan","run"])} = "plan"
    options.EvalRoot (1,1) string = "/Users/sara/local/shear-wave-estimation-evaluation"
    options.ReqmlRoot (1,1) string = "/Users/sara/local/req-ml"
    options.StudyRoot (1,1) string = ""
    options.QualityBundle (1,1) string = ""
    options.Arms (1,:) string = ["reduced14","reduced14_filtered"]
    options.CaseIDs (1,:) string = strings(1,0)
    options.M (1,1) double {mustBeMember(options.M,[2 3])} = 2
    options.StepPixels (1,1) double {mustBeInteger,mustBePositive} = 5
    options.MaximumRisks (1,:) double = [0.2 0.3 0.5]
    options.ErrorThresholdPct (1,1) double {mustBePositive} = 10
    options.MakePlots (1,1) logical = true
    options.OutputName (1,1) string = "reduced14_quality_mask_swsynth_v1"
end
assert(~isempty(options.Arms) && ...
    numel(unique(options.Arms))==numel(options.Arms) && ...
    all(ismember(options.Arms,["reduced14","reduced14_filtered"])), ...
    "QualitySynth:Arms","Select unique Reduced14 raw/filtered arms.");
assert(~isempty(options.MaximumRisks) && ...
    all(isfinite(options.MaximumRisks) & options.MaximumRisks>=0 & ...
        options.MaximumRisks<=1), ...
    "QualitySynth:Risks","MaximumRisks must be in [0,1].");
assert(strlength(options.OutputName)>0 && ...
    ~any(contains(options.OutputName,["/","\\"])), ...
    "QualitySynth:OutputName","OutputName must be one directory name.");
if options.StudyRoot==""
    options.StudyRoot=fullfile(options.EvalRoot,"studies", ...
        "reqml_frequency_bias_swsynth");
end
addpath(options.StudyRoot,"-begin");
addpath(fullfile(options.EvalRoot,"src"),"-begin");
C=swsynth_comparison_config(StudyRoot=options.StudyRoot, ...
    ReqmlRoot=options.ReqmlRoot,Arms=options.Arms, ...
    M=options.M,StepPixels=options.StepPixels);
T=C.Cases;
if ~isempty(options.CaseIDs)
    assert(numel(unique(options.CaseIDs))==numel(options.CaseIDs) && ...
        all(ismember(options.CaseIDs,T.case_id)), ...
        "QualitySynth:CaseIDs","Unknown/duplicate case IDs.");
    T=T(ismember(T.case_id,options.CaseIDs),:);
end
bundle=options.QualityBundle;
if bundle==""
    bundle=fullfile(options.ReqmlRoot,"training", ...
        "q0_v5_clean_campaign","outputs", ...
        "reduced14_quality_mask_v1","quality_mask_bundle.mat");
end
caseParts=cell(height(T)*numel(options.Arms),1);
nCase=0;
for i=1:height(T)
    for arm=options.Arms
        source=swsynth_comparison_estimate_file(C,T(i,:),arm);
        next=table(T.case_id(i),T.series(i),T.group(i), ...
            T.frequency_hz(i),arm,source,isfile(source), ...
            VariableNames=["case_id","series","group", ...
            "frequency_hz","arm","estimate_file","estimate_exists"]);
        nCase=nCase+1;
        caseParts{nCase}=next;
    end
end
cases=vertcat(caseParts{:});
missing=cases.estimate_file(~cases.estimate_exists);
if ~isfile(bundle),missing=[bundle;missing];end
out=struct("mode",options.Mode,"cases",cases, ...
    "quality_bundle",bundle,"missing_inputs",missing, ...
    "summary",table(),"calibration",table(),"output_dir","");
fprintf("SWSynth mask v1: %d cases (%d physical series), %d inputs missing.\n", ...
    height(cases),numel(unique(T.series)),numel(missing));
if ~isempty(missing),disp(missing(1:min(15,numel(missing))));end
if options.Mode=="plan"
    fprintf("Plan only. No files written, no training, no simulations.\n");
    return
end
assert(isempty(missing),"QualitySynth:MissingInputs", ...
    "Missing estimates/bundle; inspect Mode=plan before running.");
addpath(fullfile(options.ReqmlRoot,"training", ...
    "q0_v5_clean_campaign"),"-begin");
assert(~isempty(which("q0v5.quality.predictRisk")) && ...
    ~isempty(which("swseval.qualitymask.evaluateTruth")), ...
    "QualitySynth:CodePath","REQ-ML quality / SWS-Eval code not found.");
cutoffs=sort(unique(options.MaximumRisks(:)'));
root=fullfile(C.outputRoot,"quality_mask_swsynth",options.OutputName);
caseSummary=cell(height(cases),1);
caseWindows=cell(height(cases),1);
for j=1:height(cases)
    c=cases(j,:);
    destination=fullfile(root,"cases",c.case_id(1),c.arm(1), ...
        "quality_truth_result.mat");
    dataStamp=dir(c.estimate_file(1));
    bundleStamp=dir(bundle);
    identity=struct("estimate_file",c.estimate_file(1), ...
        "estimate_bytes",double(dataStamp.bytes), ...
        "estimate_date",double(dataStamp.datenum), ...
        "bundle_file",bundle,"bundle_bytes",double(bundleStamp.bytes), ...
        "bundle_date",double(bundleStamp.datenum), ...
        "arm",c.arm(1),"case_id",c.case_id(1), ...
        "max_risks",cutoffs,"error_threshold_pct",options.ErrorThresholdPct, ...
        "study_protocol","swsynth20_roi_truth_v1");
    study_identity=string(jsonencode(identity)); %#ok<NASGU>
    if isfile(destination)
        saved=load(destination,"analysis","roi_summary", ...
            "roi_windows","study_identity");
        assert(isfield(saved,"study_identity") && ...
            string(saved.study_identity)==study_identity && ...
            isfield(saved,"analysis") && ...
            isfield(saved,"roi_summary") && isfield(saved,"roi_windows"), ...
            "QualitySynth:Stale","Existing output differs: %s",destination);
        analysis=saved.analysis;
        roi_summary=saved.roi_summary;
        roi_windows=saved.roi_windows;
        fprintf("[%d/%d] %s / %s: resumed\n", ...
            j,height(cases),c.case_id(1),c.arm(1));
    else
        s=load(c.estimate_file(1),"result");
        assert(isfield(s,"result") && ...
            isfield(s.result,"metadata") && ...
            isfield(s.result.metadata,"comparison_case_id") && ...
            string(s.result.metadata.comparison_case_id)==c.case_id(1), ...
            "QualitySynth:CaseIdentity","Wrong saved estimate case: %s", ...
            c.estimate_file(1));
        analysis=swseval.qualitymask.analyzeResult(s.result,bundle, ...
            Arm=c.arm(1),MaximumRisks=cutoffs);
        [truth,rois]=truthAndROIs(c.group(1), ...
            double(T.reference_cs_m_s(T.case_id==c.case_id(1))),analysis);
        summaryParts=cell(numel(rois),1);
        windowParts=cell(numel(rois),1);
        for ri=1:numel(rois)
            selection=swseval.roi.mask(rois(ri),s.result);
            if string(rois(ri).name)=="interface"
                % Exactly on the material boundary, pointwise truth is
                % ambiguous; keep adjacent pixels but not the center line.
                selection=selection & abs(analysis.z_mm-25)>0.25;
            end
            [S,W]=swseval.qualitymask.evaluateTruth( ...
                analysis,selection,truth, ...
                ErrorThresholdPct=options.ErrorThresholdPct);
            S=addvars(S,repmat(c.case_id(1),height(S),1), ...
                repmat(c.series(1),height(S),1), ...
                repmat(c.group(1),height(S),1), ...
                repmat(c.arm(1),height(S),1), ...
                repmat(c.frequency_hz(1),height(S),1), ...
                repmat(string(rois(ri).name),height(S),1), ...
                Before=1,NewVariableNames=["case_id","series", ...
                "group","arm","frequency_hz","roi"]);
            W=addvars(W,repmat(c.case_id(1),height(W),1), ...
                repmat(c.series(1),height(W),1), ...
                repmat(c.group(1),height(W),1), ...
                repmat(c.arm(1),height(W),1), ...
                repmat(c.frequency_hz(1),height(W),1), ...
                repmat(string(rois(ri).name),height(W),1), ...
                Before=1,NewVariableNames=["case_id","series", ...
                "group","arm","frequency_hz","roi"]);
            summaryParts{ri}=S;
            windowParts{ri}=W;
        end
        roi_summary=vertcat(summaryParts{:});
        roi_windows=vertcat(windowParts{:});
        folder=string(fileparts(destination));
        if ~isfolder(folder),mkdir(folder);end
        partial=destination+".partial.mat";
        assert(~isfile(partial),"QualitySynth:Partial", ...
            "Inspect unfinished output: %s",partial);
        save(partial,"analysis","roi_summary", ...
            "roi_windows","study_identity","-v7.3");
        assert(~isfile(destination),"QualitySynth:Race", ...
            "Output appeared: %s",destination);
        [ok,msg]=movefile(partial,destination);
        assert(ok,"QualitySynth:Write","Unable to save: %s",msg);
        fprintf("[%d/%d] %s / %s: evaluated vs truth\n", ...
            j,height(cases),c.case_id(1),c.arm(1));
    end
    if options.MakePlots
        figFile=fullfile(fileparts(destination),"risk_vs_true_error.png");
        if ~isfile(figFile)
            [truth,~]=truthAndROIs(c.group(1), ...
                double(T.reference_cs_m_s(T.case_id==c.case_id(1))),analysis);
            plotTruth(analysis,truth,figFile,c.case_id(1)+ ...
                " | "+c.arm(1));
        end
    end
    caseSummary{j}=roi_summary;
    caseWindows{j}=roi_windows;
end
out.summary=vertcat(caseSummary{:});
allWindows=vertcat(caseWindows{:});
out.calibration=calibrationTable(allWindows);
if height(T)==20
    scope="all20_"+strjoin(options.Arms,"_");
else
    scope="selected_"+strjoin(T.case_id,"_");
    if strlength(scope)>130
        scope="selected"+string(height(T))+"_"+T.case_id(1);
    end
    scope=scope+"_"+strjoin(options.Arms,"_");
end
destination=fullfile(root,"aggregates",scope);
out.output_dir=destination;
manifest=fullfile(destination,"study_manifest.mat");
scope_identity=string(jsonencode(struct( ...
    "case_ids",T.case_id,"arms",options.Arms, ...
    "m",options.M,"step_pixels",options.StepPixels, ...
    "quality_bundle",bundle,"cutoffs",cutoffs, ...
    "error_threshold_pct",options.ErrorThresholdPct, ...
    "case_identity",cases.estimate_file))); %#ok<NASGU>
if isfile(manifest)
    v=load(manifest,"scope_identity");
    assert(isfield(v,"scope_identity") && ...
        v.scope_identity==scope_identity, ...
        "QualitySynth:AggregateStale", ...
        "Aggregate scope exists for different settings: %s",destination);
else
    assert(~isfolder(destination),"QualitySynth:PartialAggregate", ...
        "Inspect incomplete aggregate directory: %s",destination);
    mkdir(destination);
    writetable(out.summary,fullfile(destination,"risk_vs_truth_by_roi.csv"));
    writetable(out.calibration,fullfile(destination,"risk_calibration_bins.csv"));
    save(fullfile(destination,"risk_vs_truth_windows.mat"), ...
        "allWindows","-v7.3");
    save(manifest,"scope_identity","cases","-v7.3");
end
fprintf("Completed %d truth comparisons. Summary: %s\n", ...
    height(cases),destination);
end

function [truth,rois]=truthAndROIs(group,homogeneousCs,A)
sz=size(A.original_sws_map);
if group=="plane_bilayer"
    assert(abs(homogeneousCs-1.8)<1e-10,"QualitySynth:Bilayer", ...
        "Expected frozen 1.8/3.0 m/s bilayer.");
    z=double(A.z_mm(:));
    profile=1.8*ones(numel(z),1);
    profile(z>=25)=3;
    truth=repmat(profile,1,sz(2));
    [rois,~]=swsynth_comparison_rois(group,homogeneousCs);
    rois(end+1)=swseval.roi.rectangle("interface", ...
        Center=[25 25],Size=[10 5],Units="mm");
else
    assert(ismember(group,["point_homogeneous","plane_homogeneous"]), ...
        "QualitySynth:Group","Unknown synthetic group.");
    truth=homogeneousCs*ones(sz);
    [rois,~]=swsynth_comparison_rois(group,homogeneousCs);
end
end

function calibration=calibrationTable(W)
bins=[0 .1 .2 .3 .4 .5 .7 1+eps(1)];
groups=unique(W(:,["arm","group","roi","frequency_hz"]),"rows","stable");
entries=cell(height(groups)*(numel(bins)-1),1);n=0;
for i=1:height(groups)
    g=groups(i,:);
    selected=W.arm==g.arm & W.group==g.group & ...
        W.roi==g.roi & W.frequency_hz==g.frequency_hz & W.risk_scored;
    for b=1:numel(bins)-1
        idx=selected & W.risk_probability>=bins(b) & ...
            W.risk_probability<bins(b+1);
        n=n+1;
        entries{n}=table(g.arm,g.group,g.roi,g.frequency_hz, ...
            bins(b),min(bins(b+1),1),nnz(idx), ...
            mean(W.risk_probability(idx),"omitnan"), ...
            mean(double(W.high_error(idx)),"omitnan"), ...
            VariableNames=["arm","group","roi","frequency_hz", ...
            "risk_bin_low","risk_bin_high","window_count", ...
            "mean_predicted_risk","observed_high_error_fraction"]);
    end
end
calibration=vertcat(entries{1:n});
end

function plotTruth(A,truth,outputFile,plotTitle)
fig=figure("Visible","off","Color","w", ...
    "Position",[50 50 1740 450]);
closeFig=onCleanup(@()close(fig)); %#ok<NASGU>
t=tiledlayout(fig,1,4,"TileSpacing","compact","Padding","compact");
title(t,plotTitle,"Interpreter","none");
speed=A.original_sws_map;
err=100*abs(speed-truth)./truth;
showMap(nexttile(t),A,speed,"SWS [m/s]",[1.5 4.5]);
showMap(nexttile(t),A,err,"Actual error [%]",[0 30]);
showMap(nexttile(t),A,A.risk_map,"Predicted risk",[0 1]);
[~,k]=min(abs(A.max_risks-0.3));
showMap(nexttile(t),A,A.masked_sws_maps(:,:,k), ...
    "Retained SWS | risk <= "+num2str(A.max_risks(k)),[1.5 4.5]);
exportgraphics(fig,outputFile,"Resolution",160);
end

function showMap(ax,A,data,ttl,limits)
im=imagesc(ax,A.x_mm,A.z_mm,double(data));
set(im,"AlphaData",double(isfinite(data)));
set(ax,"YDir","reverse","Color","w");
axis(ax,"image");clim(ax,limits);colorbar(ax);
xlabel(ax,"x [mm]");ylabel(ax,"z [mm]");title(ax,ttl);
end
