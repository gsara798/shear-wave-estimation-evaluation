function testFrozen85PolicyFromSeparateContract(t)
[paths,cleaner]=fixturePolicy(); %#ok<ASGLU>
P=load_adaptive_req_full21_mask_policy( ...
    Policy="validation85_posthoc", ...
    ReleaseDirectory=paths.release,ReqMLRoot=paths.root);
verifyEqual(t,P.cutoff,.2300157481407481,AbsTol=1e-15);
verifyEqual(t,P.original_cutoff,.1476418912,AbsTol=1e-12);
verifyTrue(t,P.posthoc_secondary);
verifyEqual(t,P.selection_status,"posthoc_after_experimental_review");
verifyTrue(t,isfile(P.contract_file));
Q=load_adaptive_req_full21_mask_policy( ...
    Policy="original80", ...
    ReleaseDirectory=paths.release,ReqMLRoot=paths.root);
verifyFalse(t,Q.posthoc_secondary);
verifyEqual(t,Q.cutoff,.1476418912,AbsTol=1e-12);
% The old release remains the same for both policies.
verifyEqual(t,Q.mask_model_id,P.mask_model_id);
verifyEqual(t,Q.regression_model_id,P.regression_model_id);
end

