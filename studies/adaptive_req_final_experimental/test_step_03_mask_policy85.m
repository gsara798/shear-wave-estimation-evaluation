function testReThresholdKeepsUnscoredUnchanged(t)
A=fixtureScores();
Aold=A;
B=rethreshold_adaptive_req_full21_quality_mask( ...
    A,.23,ExpectedOriginalCutoff=.1476418912);
verifyEqual(t,B.cutoff,.23,AbsTol=1e-14);
verifyEqual(t,B.original_valid_count,3);
verifyEqual(t,B.retained_count,2);
verifyEqual(t,B.rejected_count,0);
verifyEqual(t,B.unscored_count,1);
verifyEqual(t,B.invalid_count,1);
verifyEqual(t,B.coverage_on_original_valid,2/3,AbsTol=1e-12);
verifyEqual(t,B.risk_score_map,A.risk_score_map);
verifyEqual(t,B.original_sws_map,A.original_sws_map);
verifyEqual(t,B.unscored_mask,A.unscored_mask);
verifyTrue(t,isnan(B.masked_sws_map(2,1)));
verifyTrue(t,isnan(B.masked_sws_map(2,2)));
verifyEqual(t,B.masked_sws_map(1,2),3);
verifyEqual(t,A,Aold); % source original 80% was not changed
end

