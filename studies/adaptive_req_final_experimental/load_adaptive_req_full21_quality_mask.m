function release=load_adaptive_req_full21_quality_mask(options)
%LOAD_ADAPTIVE_REQ_FULL21_QUALITY_MASK Load only the frozen Full21 classifier.
% The regressor is deliberately NOT loaded; q has already been predicted in
% stage 02. Model/cutoff were frozen before TEST; never tune on experiments.
arguments
    options.ReleaseDirectory (1,1) string
    options.Verbose (1,1) logical = true
end
folder=options.ReleaseDirectory;
modelFile=fullfile(folder,"req_model.mat");
maskFile=fullfile(folder,"quality_mask.mat");
specFile=fullfile(folder,"operating_spec.mat");
manifestFile=fullfile(folder,"deployment_manifest.json");
assert(all(isfile([modelFile;maskFile;specFile;manifestFile])), ...
    "AdaptiveREQ:MaskReleaseMissing", ...
    "Incomplete published Full21 release: %s",folder);

if options.Verbose
    fprintf("    [MASK] Reading operating_spec.mat and release manifest ...\n");
end
P=load(specFile,"operating_spec");
assert(isfield(P,"operating_spec") && isstruct(P.operating_spec), ...
    "AdaptiveREQ:MaskMissingSpec","Published operating spec is invalid.");
S=P.operating_spec;
manifest=jsondecode(fileread(manifestFile));

names=string(S.req_predictor_names(:));
maskNames=string(S.mask_predictor_names(:));
cutoff=double(S.frozen_risk_threshold);
assert(string(S.release_id)=="adaptive_req_full21_v1" && ...
    string(manifest.release_id)==string(S.release_id) && ...
    numel(names)==21 && numel(unique(names))==21 && ...
    numel(maskNames)==22 && ...
    isequal(maskNames,[names;"reqml_q_pred"]) && ...
    all(ismember(names,maskNames)) && ...
    string(S.threshold_source)=="independent VALIDATION" && ...
    string(S.regression_model_id)==string(manifest.model_id) && ...
    string(S.mask_model_id)==string(manifest.mask_id) && ...
    isfinite(cutoff) && cutoff>0 && cutoff<1 && ...
    abs(cutoff-double(manifest.risk_threshold))<1e-12 && ...
    isfield(manifest,"model_predictors") && ...
    isequal(string(manifest.model_predictors(:)),names) && ...
    isfield(manifest,"mask_predictors") && ...
    isequal(string(manifest.mask_predictors(:)),maskNames), ...
    "AdaptiveREQ:MaskFrozenContract", ...
    "Published risk threshold, release identity or predictor order differs.");

modelInfo=dir(modelFile);
maskInfo=dir(maskFile);
assert(isscalar(modelInfo) && isscalar(maskInfo), ...
    "AdaptiveREQ:MaskReleaseFiles","Expected one file per release artifact.");
if isfield(manifest,"model_size_bytes")
    assert(double(modelInfo.bytes)==double(manifest.model_size_bytes), ...
        "AdaptiveREQ:MaskModelSize","Released q-model size differs from manifest.");
end
if isfield(manifest,"mask_size_bytes")
    assert(double(maskInfo.bytes)==double(manifest.mask_size_bytes), ...
        "AdaptiveREQ:MaskClassifierSize", ...
        "Released classifier size differs from manifest.");
end

if options.Verbose
    fprintf("    [MASK] Loading frozen risk classifier (%.2f GiB on disk) ...\n", ...
        double(maskInfo.bytes)/1024^3);
end
C=load(maskFile,"classifier","metadata");
assert(isfield(C,"classifier") && isfield(C,"metadata") && ...
    isstruct(C.metadata), ...
    "AdaptiveREQ:MaskFile","Published quality_mask.mat is invalid.");
meta=C.metadata;
assert(isequal(string(meta.predictor_names(:)),maskNames) && ...
    string(meta.classifier_id)==string(S.mask_model_id) && ...
    double(meta.training_rows)==5540400 && ...
    double(meta.num_trees)==160 && ...
    double(meta.min_leaf_size)==8 && ...
    double(meta.risk_error_threshold_pct)==10 && ...
    ~logical(meta.test_used) && ~logical(meta.validation_used) && ...
    isequal(double(C.classifier.ClassNames(:)),[0;1]) && ...
    double(S.positive_class)==1, ...
    "AdaptiveREQ:MaskMetadata", ...
    "Saved classifier differs from frozen TRAIN-only mask contract.");

release=struct( ...
    "classifier",C.classifier, ...
    "predictor_names",names, ...
    "mask_predictor_names",maskNames, ...
    "cutoff",cutoff, ...
    "regression_model_id",string(S.regression_model_id), ...
    "mask_model_id",string(S.mask_model_id), ...
    "model_file",modelFile, ...
    "mask_file",maskFile, ...
    "spec_file",specFile, ...
    "manifest_file",manifestFile, ...
    "release_id",string(S.release_id));
if options.Verbose
    fprintf("    [MASK] Loaded: 21 spectral/operational + predicted q; cutoff %.17g\n",cutoff);
    fprintf("    [MASK] Risk score is not a calibrated probability.\n");
end
end
