function Q=rethreshold_adaptive_req_full21_quality_mask(original,cutoff,options)
%RETHRESHOLD_ADAPTIVE_REQ_FULL21_QUALITY_MASK Reuse saved Full21 risk scores.
% Recomputes ONLY the keep/reject/NaN maps and summary for a separately
% frozen VALIDATION operating point. Does NOT evaluate the classifier.
% Original 80% checkpoint is never changed.
arguments
    original (1,1) struct
    cutoff (1,1) double {mustBeFinite,mustBeGreaterThan(cutoff,0), ...
        mustBeLessThan(cutoff,1)}
    options.ExpectedOriginalCutoff (1,1) double = NaN
end
required=["risk_score_map","original_sws_map","masked_sws_map", ...
    "original_valid_mask","retained_mask","rejected_mask", ...
    "unscored_mask","invalid_mask","q_map","x_mm","z_mm", ...
    "cutoff","release_id","regression_model_id", ...
    "original_valid_count","invalid_count","retained_count", ...
    "rejected_count","unscored_count","scored_count"];
assert(all(isfield(original,cellstr(required))), ...
    "AdaptiveREQ:RethresholdSchema","Original frozen mask is incomplete.");
if isfinite(options.ExpectedOriginalCutoff)
    assert(abs(double(original.cutoff)- ...
        options.ExpectedOriginalCutoff)<1e-12, ...
        "AdaptiveREQ:RethresholdSourceCutoff", ...
        "Source mask does not have the expected original frozen cutoff.");
end
cs=double(original.original_sws_map);
risk=double(original.risk_score_map);
base=logical(original.original_valid_mask);
q=double(original.q_map);
oldKeep=logical(original.retained_mask);
oldReject=logical(original.rejected_mask);
oldUnscored=logical(original.unscored_mask);
invalid=logical(original.invalid_mask);
assert(isequal(size(cs),size(risk),size(base),size(q), ...
    size(oldKeep),size(oldReject),size(oldUnscored),size(invalid)) && ...
    numel(original.x_mm)==size(cs,2) && ...
    numel(original.z_mm)==size(cs,1) && ...
    string(original.release_id)=="adaptive_req_full21_v1" && ...
    isfinite(double(original.cutoff)) && ...
    double(original.cutoff)>0 && double(original.cutoff)<1 && ...
    all(isfinite(cs(base))&cs(base)>0) && ...
    all(isfinite(q(base))) && ...
    all(risk(isfinite(risk))>=0&risk(isfinite(risk))<=1), ...
    "AdaptiveREQ:RethresholdGrid", ...
    "Original Full21 mask maps, grid, scores or model release are invalid.");
scored=base&isfinite(risk);
oldThreshold=double(original.cutoff);
assert(isequal(oldKeep,scored&risk<=oldThreshold) && ...
    isequal(oldReject,scored&risk>oldThreshold) && ...
    isequal(oldUnscored,base&~scored) && ...
    isequal(invalid,~base) && ...
    nnz(base)==double(original.original_valid_count) && ...
    nnz(oldKeep)==double(original.retained_count) && ...
    nnz(oldReject)==double(original.rejected_count) && ...
    nnz(oldUnscored)==double(original.unscored_count) && ...
    nnz(scored)==double(original.scored_count) && ...
    nnz(invalid)==double(original.invalid_count) && ...
    isequaln(double(original.masked_sws_map), ...
        applyMask(cs,oldKeep)), ...
    "AdaptiveREQ:RethresholdSourceLabels", ...
    "Original 80%% map does not reproduce its saved scores/coverage.");
Q=original;
Q.cutoff=double(cutoff);
Q.retained_mask=scored&risk<=cutoff;
Q.rejected_mask=scored&risk>cutoff;
Q.unscored_mask=base&~scored;
Q.masked_sws_map=applyMask(cs,Q.retained_mask);
Q.retained_count=nnz(Q.retained_mask);
Q.rejected_count=nnz(Q.rejected_mask);
Q.unscored_count=nnz(Q.unscored_mask);
Q.invalid_count=nnz(invalid);
Q.scored_count=nnz(scored);
Q.original_valid_count=nnz(base);
if nnz(base)>0
    Q.coverage_on_original_valid=nnz(Q.retained_mask)/nnz(base);
    Q.scored_fraction_on_original_valid=nnz(scored)/nnz(base);
else
    Q.coverage_on_original_valid=NaN;
    Q.scored_fraction_on_original_valid=NaN;
end
assert(nnz(Q.retained_mask)+nnz(Q.rejected_mask)+ ...
    nnz(Q.unscored_mask)==nnz(base) && ...
    ~any(Q.retained_mask&Q.rejected_mask,"all"), ...
    "AdaptiveREQ:RethresholdPartition", ...
    "New cutoff did not partition scored and unscored SWS.");
end

function masked=applyMask(original,keep)
masked=original;
masked(~keep)=NaN;
end
