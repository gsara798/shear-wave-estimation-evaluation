function cfg=compare_models_500hz_config(options)
%COMPARE_MODELS_500HZ_CONFIG Shared, path-safe six-acquisition comparison.
% No IQ processing or training. Uses existing adaptive_req_final_unfiltered_v1.
% DataRoot and ReqMLRoot resolve from sibling checkouts, never user names.
arguments
    options.DataRoot (1,1) string = ""
    options.ReqMLRoot (1,1) string = ""
    options.SelectedCaseIDs (1,:) string = strings(1,0)
    options.FrequencyHz (1,1) double {mustBePositive} = 500
    options.M (1,1) double {mustBePositive} = 2
    options.StepPixels (1,1) double {mustBeInteger,mustBePositive} = 3
end
studyDir=string(fileparts(mfilename("fullpath")));
evalRoot=string(fileparts(fileparts(studyDir)));
localBase=string(fileparts(evalRoot));
dataRoot=options.DataRoot;
reqRoot=options.ReqMLRoot;
if dataRoot=="",dataRoot=fullfile(localBase,"experimental-data-reorganized");end
if reqRoot=="",reqRoot=fullfile(localBase,"req-ml");end
assert(options.FrequencyHz==round(options.FrequencyHz) && ...
    ismember(options.FrequencyHz,[300 400 500 600]) && ...
    ismember(options.M,[1 2 3]), ...
    "AdaptiveREQ:Compare500Settings", ...
    "Use a frequency in [300 400 500 600] and M in [1 2 3].");
allCases=[
    "2026Feb27_homo_10perc_sp"
    "2026Feb27_homo_10perc_rswe"
    "2026Feb27_homo_5perc_sp"
    "2026Feb27_homo_5perc_rswe"
    "2026Feb27_dl_sp"
    "2026Feb27_dl_rswe"
];
chosen=string(options.SelectedCaseIDs(:));
if isempty(chosen),chosen=allCases;end
assert(all(ismember(chosen,allCases)) && ...
    numel(unique(chosen))==numel(chosen), ...
    "AdaptiveREQ:Compare500Cases", ...
    "Select only unique February-27 homogeneous/bilayer SP/RSWE IDs.");
assert(isfolder(fullfile(evalRoot,"src")) && ...
    isfolder(fullfile(reqRoot,"src")), ...
    "AdaptiveREQ:Compare500Dependencies", ...
    "Expected sibling shear-wave-estimation-evaluation and REQ-ML checkouts.");
studyID="adaptive_req_final_experimental_v1";
processedRun="adaptive_req_final_unfiltered_v1";
arms=["adaptive_req_full21_unfiltered_v1", ...
      "adaptive_req_full21_clean_v1", ...
      "legacy_q0_v1"];
modelClean=fullfile(reqRoot,"training","adaptive_req_final_v1", ...
    "noise_free_full21_v1","outputs","clean_v1", ...
    "adaptive_req_full21_clean_model.mat");
modelLegacy=fullfile(reqRoot,"models","legacy","model_bundle.mat");
manifestLegacy=fullfile(reqRoot,"models","legacy","training_manifest.json");
modelsOriginal=fullfile(reqRoot,"models","adaptive_req_full21_v1","req_model.mat");

jobs=table();
for caseID=chosen.'
    caseRoot=fullfile(dataRoot,"2026-02-27",caseID);
    sample=fullfile(caseRoot,"processed",processedRun, ...
        sprintf("%gHz",options.FrequencyHz),"wavefield_sample.mat");
    estBase=fullfile(caseRoot,"estimates",studyID,"REQ-ML");
    dirs=strings(3,1);
    for k=1:3
        dirs(k)=fullfile(estBase,arms(k), ...
            sprintf("%gHz",options.FrequencyHz), ...
            "M"+string(options.M),"step"+string(options.StepPixels), ...
            "reqml_result.mat");
    end
    jobs=[jobs;table(caseID, ...
        repmat(options.FrequencyHz,1),repmat(options.M,1), ...
        repmat(options.StepPixels,1),sample,dirs(1),dirs(2),dirs(3), ...
        isfile(sample),isfile(dirs(1)),isfile(dirs(2)), ...
        isfile(dirs(3)), ...
        'VariableNames',["case_id","frequency_hz","M","step_pixels", ...
        "sample_file","original_file","clean_file","legacy_file", ...
        "sample_ready","original_ready","clean_ready","legacy_ready"])]; %#ok<AGROW>
end
output=fullfile(dataRoot,"analysis",studyID, ...
    "three_model_unfiltered_comparison_v1", ...
    sprintf("%gHz",options.FrequencyHz), ...
    "M"+string(options.M),"step"+string(options.StepPixels));
cfg=struct("study_dir",studyDir,"evaluation_root",evalRoot, ...
    "reqml_root",reqRoot,"data_root",dataRoot,"study_id",studyID, ...
    "processed_run",processedRun,"frequency_hz",options.FrequencyHz, ...
    "M",options.M,"step_pixels",options.StepPixels, ...
    "case_ids",chosen,"arms",arms, ...
    "model_clean",modelClean,"model_legacy",modelLegacy, ...
    "manifest_legacy",manifestLegacy, ...
    "model_original",modelsOriginal, ...
    "output_directory",output,"jobs",jobs);
end
