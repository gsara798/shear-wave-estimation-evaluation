function Q=score_adaptive_req_full21_quality_mask(result,release)
%SCORE_ADAPTIVE_REQ_FULL21_QUALITY_MASK Apply frozen mask to saved Full21 SWS.
%
% Reuses exact stage-02 patch features and its SAVED predicted q.
% No q inference, no spectral feature extraction, no truth, no new cutoff.
% Risk score is an ensemble score, NOT a calibrated probability.
% Only finite original SWS-valid windows are eligible. Keep, reject, and
% unscored are mutually exclusive and partition original-valid windows.
arguments
    result (1,1) struct
    release (1,1) struct
end
required=["patch_examples","q_map","cs_map","valid_mask", ...
    "x_mm","z_mm","metadata"];
assert(all(isfield(result,cellstr(required))), ...
    "AdaptiveREQ:MaskResultFields","Stage-02 result lacks required fields.");
assert(all(isfield(release,cellstr(["classifier","predictor_names", ...
    "mask_predictor_names","cutoff","regression_model_id"]))), ...
    "AdaptiveREQ:MaskReleaseFields","Frozen classifier package is incomplete.");
assert(isfield(result.metadata,"model_provenance_id") && ...
    string(result.metadata.model_provenance_id)== ...
    string(release.regression_model_id), ...
    "AdaptiveREQ:MaskWrongRegressor", ...
    "Saved SWS predictions were not produced by the paired frozen Full21 model.");
assert(isfield(result.metadata,"experimental_mask_applied") && ...
    ~logical(result.metadata.experimental_mask_applied), ...
    "AdaptiveREQ:MaskAlreadyApplied","Input estimate is not the original raw SWS map.");

cs=double(result.cs_map);
q=double(result.q_map);
valid=logical(result.valid_mask);
shape=size(cs);
assert(ismatrix(cs) && ~isempty(cs) && ...
    isequal(size(q),shape) && isequal(size(valid),shape) && ...
    numel(result.x_mm)==shape(2) && numel(result.z_mm)==shape(1), ...
    "AdaptiveREQ:MaskMapShape","SWS, q, mask, or map coordinates disagree.");
baseValid=valid & isfinite(cs) & cs>0 & isfinite(q);
E=result.patch_examples;
assert(istable(E) && height(E)>0 && ...
    all(ismember(["map_ix","map_iz"], ...
    string(E.Properties.VariableNames))), ...
    "AdaptiveREQ:MaskExamples","Missing patch-center indices in estimate.");
ix=double(E.map_ix(:));
iz=double(E.map_iz(:));
assert(all(isfinite(ix)&isfinite(iz)) && ...
    all(ix==round(ix) & iz==round(iz)) && ...
    all(ix>=1 & ix<=shape(2) & iz>=1 & iz<=shape(1)), ...
    "AdaptiveREQ:MaskPatchIndices","Invalid patch-center indices.");
linear=sub2ind(shape,iz,ix);
assert(numel(unique(linear))==numel(linear) && ...
    numel(linear)==numel(baseValid), ...
    "AdaptiveREQ:MaskGridCoverage", ...
    "Saved patch examples must map exactly once to every map pixel.");
assert(isequal(sort(linear(:)),(1:numel(baseValid)).'), ...
    "AdaptiveREQ:MaskMapIndices","Patch map is incomplete or out of order.");

names=string(release.predictor_names(:));
maskNames=string(release.mask_predictor_names(:));
assert(numel(names)==21 && isequal(maskNames,[names;"reqml_q_pred"]), ...
    "AdaptiveREQ:MaskPredictorOrder", ...
    "Expected 21 frozen Full21 predictors followed by saved predicted q.");
available=string(E.Properties.VariableNames);
missing=setdiff(names,available);
assert(isempty(missing),"AdaptiveREQ:MaskMissingFeatures", ...
    "Saved SWS estimate is missing frozen mask features: %s", ...
    strjoin(missing,", "));
X=nan(height(E),22);
for k=1:21
    v=E.(char(names(k)));
    assert((isnumeric(v) || islogical(v)) && ...
        isvector(v) && numel(v)==height(E), ...
        "AdaptiveREQ:MaskFeatureShape", ...
        "Predictor %s has wrong type or shape.",names(k));
    X(:,k)=double(v(:));
end
% q was predicted by the frozen q model in stage 02. Do not predict it again.
X(:,22)=q(linear);
if ismember("q_pred",available)
    assert(all(abs(double(E.q_pred(:))-X(:,22))<1e-12 | ...
        (isnan(double(E.q_pred(:))) & isnan(X(:,22)))), ...
        "AdaptiveREQ:MaskQMismatch","A saved per-patch q disagrees with q_map.");
end

eligible=baseValid(linear)&all(isfinite(X),2);
score=nan(shape);
if any(eligible)
    [~,allScores]=predict(release.classifier,X(eligible,:));
    posClass=find(double(release.classifier.ClassNames(:))==1);
    assert(isscalar(posClass),"AdaptiveREQ:MaskPositiveClass", ...
        "Classifier must have the risk-positive class 1.");
    values=double(allScores(:,posClass));
    assert(numel(values)==nnz(eligible) && ...
        all(isfinite(values)&values>=0&values<=1), ...
        "AdaptiveREQ:MaskInvalidScores", ...
        "Risk scores must be finite and lie in [0,1].");
    score(linear(eligible))=values;
end

scored=baseValid&isfinite(score);
retained=scored&score<=double(release.cutoff);
rejected=scored&score>double(release.cutoff);
unscored=baseValid&~scored;
invalid=~baseValid;
assert(~any(retained&rejected,"all") && ...
    nnz(retained)+nnz(rejected)+nnz(unscored)==nnz(baseValid), ...
    "AdaptiveREQ:MaskPartition", ...
    "Retained, rejected and unscored must partition originally valid SWS.");
maskedSws=cs;
maskedSws(~retained)=NaN;
coverage=NaN;
if nnz(baseValid)>0,coverage=nnz(retained)/nnz(baseValid);end
scoringCoverage=NaN;
if nnz(baseValid)>0,scoringCoverage=nnz(scored)/nnz(baseValid);end

Q=struct( ...
    "risk_score_map",score, ...
    "original_sws_map",cs, ...
    "masked_sws_map",maskedSws, ...
    "original_valid_mask",baseValid, ...
    "retained_mask",retained, ...
    "rejected_mask",rejected, ...
    "unscored_mask",unscored, ...
    "invalid_mask",invalid, ...
    "q_map",q, ...
    "x_mm",double(result.x_mm), ...
    "z_mm",double(result.z_mm), ...
    "cutoff",double(release.cutoff), ...
    "score_type","ensemble_risk_score_not_calibrated_probability", ...
    "regression_model_id",string(release.regression_model_id), ...
    "release_id",string(release.release_id), ...
    "original_valid_count",nnz(baseValid), ...
    "invalid_count",nnz(invalid), ...
    "retained_count",nnz(retained), ...
    "rejected_count",nnz(rejected), ...
    "unscored_count",nnz(unscored), ...
    "scored_count",nnz(scored), ...
    "coverage_on_original_valid",coverage, ...
    "scored_fraction_on_original_valid",scoringCoverage);
end
