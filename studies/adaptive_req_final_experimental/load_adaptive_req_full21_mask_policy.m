function policy=load_adaptive_req_full21_mask_policy(options)
%LOAD_ADAPTIVE_REQ_FULL21_MASK_POLICY Read only frozen operating metadata.
% No large trained classifier/regressor is loaded in this function.
% Original 80% release stays unchanged; 85% uses a separately frozen
% VALIDATION contract in the REQ-ML training campaign (post-hoc policy).
arguments
    options.Policy (1,1) string = "validation85_posthoc"
    options.ReleaseDirectory (1,1) string
    options.ReqMLRoot (1,1) string
end
mode=options.Policy;
assert(ismember(mode,["validation85_posthoc","original80"]), ...
    "AdaptiveREQ:MaskPolicyName", ...
    "Choose Policy=validation85_posthoc or original80.");
specFile=fullfile(options.ReleaseDirectory,"operating_spec.mat");
manifestFile=fullfile(options.ReleaseDirectory,"deployment_manifest.json");
assert(isfile(specFile) && isfile(manifestFile), ...
    "AdaptiveREQ:MaskPolicyRelease","Original published Full21 release is absent.");
P=load(specFile,"operating_spec");
assert(isfield(P,"operating_spec"), ...
    "AdaptiveREQ:MaskPolicyRelease","Full21 operating spec is missing.");
S=P.operating_spec;
J=jsondecode(fileread(manifestFile));
original=double(S.frozen_risk_threshold);
assert(string(S.release_id)=="adaptive_req_full21_v1" && ...
    string(J.release_id)==string(S.release_id) && ...
    string(S.threshold_source)=="independent VALIDATION" && ...
    numel(S.req_predictor_names)==21 && ...
    numel(S.mask_predictor_names)==22 && ...
    isequal(string(S.mask_predictor_names(:)), ...
        [string(S.req_predictor_names(:));"reqml_q_pred"]) && ...
    string(S.regression_model_id)==string(J.model_id) && ...
    string(S.mask_model_id)==string(J.mask_id) && ...
    isfinite(original) && original>0 && original<1 && ...
    abs(original-double(J.risk_threshold))<1e-12, ...
    "AdaptiveREQ:MaskPolicyRelease","Published Full21 contract is inconsistent.");
policy=struct("name",mode, ...
    "cutoff",original,"original_cutoff",original, ...
    "release_id",string(S.release_id), ...
    "regression_model_id",string(S.regression_model_id), ...
    "mask_model_id",string(S.mask_model_id), ...
    "contract_file","", ...
    "contract_file_identity",struct(), ...
    "selection_status","original_preregistered_80pct", ...
    "posthoc_secondary",false);
if mode=="original80",return,end
contractFile=fullfile(options.ReqMLRoot,"training", ...
    "adaptive_req_final_v1","quality_mask","outputs", ...
    "operating_85pct_posthoc_v2","frozen_operating_contract.mat");
assert(isfile(contractFile), ...
    "AdaptiveREQ:Mask85ContractMissing", ...
    "The 85%% VALIDATION contract has not been frozen: %s",contractFile);
C=load(contractFile,"contract");
assert(isfield(C,"contract") && isstruct(C.contract), ...
    "AdaptiveREQ:Mask85Contract","Frozen 85%% contract is missing.");
K=C.contract;
assert(string(K.id)=="adaptive_req_full21_mask_85pct_posthoc_v2" && ...
    string(K.source_partition)=="validation" && ...
    string(K.selection_status)=="posthoc_after_experimental_review" && ...
    string(K.evaluation_type)=="secondary_retrospective_same_TEST" && ...
    string(K.decision_rule)=="keep mask_score <= risk_threshold" && ...
    ~logical(K.independent_confirmatory_test) && ...
    ~logical(K.test_read_during_freeze) && ...
    ~logical(K.training_models_modified) && ...
    double(K.validation_target_retention)==.85 && ...
    abs(double(K.validation_actual_retention)-.85)<1e-10 && ...
    double(K.validation_reference_target_retention)==.80 && ...
    abs(double(K.validation_reference_threshold)-original)<1e-12 && ...
    string(K.regression_model_id)==string(S.regression_model_id) && ...
    string(K.classifier_model_id)==string(S.mask_model_id) && ...
    string(K.req_model_file)==fullfile(options.ReqMLRoot, ...
        "training","adaptive_req_final_v1","quality_mask","..", ...
        "final_model","outputs","full21_v1", ...
        "adaptive_req_full21_final_model.mat") && ...
    string(K.mask_model_file)==fullfile(options.ReqMLRoot, ...
        "training","adaptive_req_final_v1","quality_mask","outputs", ...
        "final_mask_v1","adaptive_req_full21_mask_t160_leaf08.mat") && ...
    isfinite(double(K.risk_threshold)) && ...
    double(K.risk_threshold)>original && ...
    double(K.risk_threshold)<1, ...
    "AdaptiveREQ:Mask85Contract", ...
    "The frozen 85%% policy differs from the published Full21 models or 80%% reference.");
info=dir(contractFile);
policy.cutoff=double(K.risk_threshold);
policy.contract_file=string(contractFile);
policy.contract_file_identity=struct( ...
    "path",string(contractFile),"bytes",double(info.bytes), ...
    "datenum",double(info.datenum));
policy.selection_status=string(K.selection_status);
policy.posthoc_secondary=true;
end
