function loaded = load_adaptive_req_full21_sws_bundle(options)
%LOAD_ADAPTIVE_REQ_FULL21_SWS_BUNDLE Adapt frozen Full21 for reqml.predictSWS.
%
% The published Full21 regressor has {model,model_info}, not the historical
% Q0 bundle's {model,model_metadata,predictor_names}. Its exact predictor
% order and clip range are frozen in operating_spec.mat. This adapter does
% NOT change the trained ensemble, q predictions or quantile-to-SWS method.
%
% The quality_mask.mat classifier is NOT loaded during stage 02.
% Call:
%   loaded=load_adaptive_req_full21_sws_bundle( ...
%       ReleaseDirectory="/path/to/models/adaptive_req_full21_v1");
%
arguments
    options.ReleaseDirectory (1,1) string
    options.Verbose (1,1) logical = true
end

folder = options.ReleaseDirectory;
modelFile = fullfile(folder,"req_model.mat");
maskFile = fullfile(folder,"quality_mask.mat");
specFile = fullfile(folder,"operating_spec.mat");
manifestFile = fullfile(folder,"deployment_manifest.json");
assert(all(isfile([modelFile;maskFile;specFile;manifestFile])), ...
    "AdaptiveREQ:Full21ReleaseMissing", ...
    "Incomplete Full21 release under %s",folder);

if options.Verbose
    fprintf("    [Full21] Reading frozen operating specification ...\n");
end
P = load(specFile,"operating_spec");
assert(isfield(P,"operating_spec") && isstruct(P.operating_spec), ...
    "AdaptiveREQ:Full21Spec","operating_spec.mat is missing operating_spec.");
S = P.operating_spec;
manifest = jsondecode(fileread(manifestFile));
names = string(S.req_predictor_names(:));
maskNames = string(S.mask_predictor_names(:));
clipRange = double(S.clip_range(:)');
assert(string(S.release_id)=="adaptive_req_full21_v1" && ...
    string(manifest.release_id)==string(S.release_id) && ...
    numel(names)==21 && numel(unique(names))==21 && ...
    numel(maskNames)==22 && ...
    isequal(maskNames,[names;"reqml_q_pred"]) && ...
    isequal(clipRange,[0.001 0.999]) && ...
    isfield(manifest,"model_predictors") && ...
    isequal(string(manifest.model_predictors(:)),names) && ...
    string(manifest.model_id)==string(S.regression_model_id), ...
    "AdaptiveREQ:Full21ReleaseContract", ...
    "Operating spec, manifest, predictor order or q clipping disagree.");

if options.Verbose
    info = dir(modelFile);
    fprintf("    [Full21] Loading only the q regressor (%.2f GiB on disk) ...\n", ...
        double(info.bytes)/1024^3);
end
% This is the ONLY large MAT load in stage 02. Do not call loadQ0Model:
% it expects historical field names and will refuse a correct Full21 file.
R = load(modelFile,"model","model_info");
assert(isfield(R,"model") && isfield(R,"model_info") && ...
    isstruct(R.model_info) && isstruct(R.model), ...
    "AdaptiveREQ:Full21ModelFile", ...
    "Published req_model.mat must contain model and model_info.");
info = R.model_info;
regressor = R.model;
assert(isequal(string(info.predictor_names(:)),names) && ...
    string(info.model_id)==string(S.regression_model_id) && ...
    string(info.candidate_id)=="full_21" && ...
    ~logical(info.test_used) && ...
    double(info.training_rows)==5540400 && ...
    isfield(info,"frozen_spec") && ...
    string(info.frozen_spec.filter_arm)=="unfiltered" && ...
    isequal(double(info.clip_range(:)'),clipRange) && ...
    string(regressor.model_type)=="bagged_trees" && ...
    double(regressor.num_learning_cycles)==160 && ...
    double(regressor.min_leaf_size)==2 && ...
    double(regressor.training_row_count)==5540400 && ...
    numel(regressor.mu)==21 && numel(regressor.sigma)==21, ...
    "AdaptiveREQ:Full21RegressorContract", ...
    "Published Full21 model differs from frozen unfiltered TRAIN regressor.");

% The public reqml.predictSWS API accepts a validated ModelBundle struct.
% Field aliases here describe the published model, not a retrained/repacked
% MAT file. MATLAB uses copy-on-write when the model struct is assigned.
loaded = struct( ...
    "model",regressor, ...
    "model_metadata",info, ...
    "predictor_names",names, ...
    "model_file",modelFile, ...
    "model_resolution",struct("source","adaptive_req_full21_v1_release"));
loaded = reqml.models.validateQ0ModelBundle(loaded);

if options.Verbose
    fprintf("    [Full21] Predictor order and frozen model identity verified.\n");
    fprintf("    [Full21] Model ID: %s | 21 predictors | clip [%.3f, %.3f]\n", ...
        string(info.model_id),clipRange(1),clipRange(2));
end
end
