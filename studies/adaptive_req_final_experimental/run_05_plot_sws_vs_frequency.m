%% Adaptive REQ-ML: Stage 05 - ROI SWS versus excitation frequency.
% One plot PER M and acquisition modality, with two separate conditions:
% ORIGINAL Full21 (no quality mask) and 85%-VALIDATION post-hoc masked.
% For homogeneous/ bilayer/ inclusion: soft only, hard only, both.
% 5% gelatin SOFT is RED; 10% gelatin HARD is BLUE (REQ paper convention).
% Error bars: ROI mean +/- spatial standard deviation (NOT standard error).
% Does not train, perform SWS inference, or rescore the quality mask.
%
% Mechanical reference: independent SLS stress-relaxation, six samples per
% formulation, per-frequency minimum-maximum envelopes from the REQ paper.
% The text supplies only APPROXIMATE envelope limits: 5% 1.8-2.0 m/s and
% 10% 2.8-3.2 m/s. Use an actual per-Hz CSV for EXACT paper bands.
%
% Mode="plan" lists file availability; Mode="run" reads saved maps and plots.
%% Editable settings
Mode="plan";                    % plan | run
DataRoot="/Users/sara/local/experimental-data-reorganized";
StudyID="adaptive_req_final_experimental_v1";
ModelLabel="adaptive_req_full21_unfiltered_v1";
MaskVersion="quality_mask_full21_val85_posthoc_v2";
FigureVersion="sws_frequency_full21_val85_v1";
StepPixels=3;
MValues=[1 2 3];
FrequenciesHz=[300 400 500 600];
SelectedCaseIDs=strings(1,0);   % empty: all eight
RequireMask=true;               % both original and masked by default
FigureFormats=["png","pdf"];
YLimits=[1 4.0];
Visible=false;
ContinueOnError=true;
Verbose=true;
% When exact SLS bands from six mechanical specimens are available, set
% ReferenceCSV to a 2x4-row file with columns:
% frequency_hz,material,lower_m_s,upper_m_s
% The supplied paper-text fallback is only APPROXIMATE, not exact.
ReferenceCSV="";

%% Resolve only saved maps and the already-frozen physical ROI manifest.
runTimer=tic;
assert(ismember(Mode,["plan","run"]) && ...
    all(ismember(FigureFormats,["png","pdf","fig"])) && ...
    numel(unique(FrequenciesHz))==numel(FrequenciesHz) && ...
    all(isfinite(FrequenciesHz)&FrequenciesHz>0) && ...
    numel(unique(MValues))==numel(MValues) && ...
    all(isfinite(MValues)&MValues>0) && ...
    StepPixels==fix(StepPixels) && StepPixels>0, ...
    "AdaptiveREQ:FrequencySettings","Invalid stage-05 configuration.");
studyDir=string(fileparts(mfilename("fullpath")));
evalRoot=string(fileparts(fileparts(studyDir)));
caseIDs=[
    "2026Feb27_homo_10perc_sp"
    "2026Feb27_homo_10perc_rswe"
    "2026Feb27_homo_5perc_sp"
    "2026Feb27_homo_5perc_rswe"
    "2026Feb27_dl_sp"
    "2026Feb27_dl_rswe"
    "2026Feb19_inc_sp"
    "2026Feb19_inc_rswe"
];
dates=[repmat("2026-02-27",6,1);repmat("2026-02-19",2,1)];
if isempty(SelectedCaseIDs),SelectedCaseIDs=caseIDs;end
SelectedCaseIDs=string(SelectedCaseIDs(:));
assert(all(ismember(SelectedCaseIDs,caseIDs)), ...
    "AdaptiveREQ:FrequencyCases","Unknown selected experimental case.");
jobs=table('Size',[0 9], ...
    'VariableTypes',["string","string","string","double","double", ...
        "string","string","logical","logical"], ...
    'VariableNames',["case_id","modality","phantom_type", ...
        "frequency_hz","M","estimate_file","mask_file", ...
        "estimate_exists","mask_exists"]);
for i=1:numel(caseIDs)
    id=caseIDs(i);
    if ~ismember(id,SelectedCaseIDs),continue;end
    caseRoot=fullfile(DataRoot,dates(i),id);
    if contains(id,"_homo_"),phantom="homogeneous";
    elseif contains(id,"_dl_"),phantom="bilayer";
    elseif contains(id,"_inc_"),phantom="inclusion";
    else,error("AdaptiveREQ:FrequencyCase","Unknown case type.");end
    if endsWith(id,"_rswe"),modality="rswe";
    else,modality="sp";end
    for m=MValues
        for hz=FrequenciesHz
            base=fullfile(caseRoot,"estimates",StudyID,"REQ-ML", ...
                ModelLabel,sprintf("%gHz",hz), ...
                "M"+string(m),"step"+string(StepPixels));
            maskBase=fullfile(caseRoot,"analysis",StudyID, ...
                "M"+string(m)+"_step"+string(StepPixels), ...
                MaskVersion,"masks",ModelLabel,sprintf("%gHz",hz));
            E=fullfile(base,"reqml_result.mat");
            Q=fullfile(maskBase,"risk_mask_result.mat");
            jobs(end+1,:)={id,modality,phantom,hz,m,E,Q, ...
                isfile(E),isfile(Q)}; %#ok<SAGROW>
        end
    end
end
fprintf("\n[ROI FREQUENCY] %d combinations | estimates %d | masks %d\n", ...
    height(jobs),nnz(jobs.estimate_exists),nnz(jobs.mask_exists));
fprintf("[ROI FREQUENCY] reference CSV: %s\n",ReferenceCSV);
if ReferenceCSV==""
    fprintf("[REFERENCE] Paper TEXT approximate envelopes only: 5%% 1.8-2.0, 10%% 2.8-3.2 m/s.\n");
    fprintf("[REFERENCE] Exact REQ bands require 6-sample SLS per-frequency limits in a CSV.\n");
else
    fprintf("[REFERENCE] Will load exact mechanical bands from %s\n",ReferenceCSV);
end
if Mode=="plan"
    disp(jobs(:,["case_id","frequency_hz","M","estimate_exists","mask_exists"]));
    fprintf("[PLAN] Read-only; no MAT or classifier loaded (%.2f s).\n",toc(runTimer));
    return
end
assert(isfolder(fullfile(evalRoot,"src")), ...
    "AdaptiveREQ:FrequencyRepo","Missing SWSEval src directory.");
addpath(fullfile(evalRoot,"src"),"-begin");
addpath(studyDir,"-begin");
assert(~isempty(which("adaptive_req_final_case_rois")) && ...
    ~isempty(which("render_adaptive_req_final_frequency_figures")), ...
    "AdaptiveREQ:FrequencyHelpers","Missing plotting/ROI helpers.");
if RequireMask && nnz(jobs.mask_exists)==0
    error("AdaptiveREQ:FrequencyMissingAllMasks", ...
        "No 85%% experimental masks found. Run stage 03 first.");
end
reference=makeMechanicalReference(FrequenciesHz,ReferenceCSV);
rows=cell(0,1);
statuses=strings(height(jobs),1);
errors=strings(height(jobs),1);
for j=1:height(jobs)
    id=jobs.case_id(j);hz=jobs.frequency_hz(j);m=jobs.M(j);
    if ~jobs.estimate_exists(j)
        statuses(j)="missing_estimate";continue
    end
    if RequireMask && ~jobs.mask_exists(j)
        statuses(j)="missing_mask";continue
    end
    try
        A=load(jobs.estimate_file(j),"result","inference_identity");
        assert(isfield(A,"result") && isfield(A,"inference_identity"), ...
            "AdaptiveREQ:FrequencyEstimateSchema","Saved estimate is invalid.");
        R=A.result;
        assert(isfield(R,"cs_map") && isfield(R,"valid_mask") && ...
            isfield(R,"x_mm") && isfield(R,"z_mm") && ...
            isfield(R,"metadata") && ...
            string(R.metadata.experimental_case_id)==id && ...
            string(R.metadata.experimental_study_id)==StudyID && ...
            string(R.metadata.experimental_arm)==ModelLabel && ...
            double(R.metadata.frequency_hz)==hz && ...
            double(R.metadata.M)==m && ...
            double(R.metadata.step_pixels)==StepPixels, ...
            "AdaptiveREQ:FrequencyEstimateIdentity", ...
            "Stage-02 SWS map identity mismatch.");
        X=double(R.x_mm(:)');
        Z=double(R.z_mm(:));
        sws=double(R.cs_map);
        valid=logical(R.valid_mask);
        assert(isequal(size(sws),size(valid), ...
            [numel(Z),numel(X)]) && ...
            all(diff(X)>0) && all(diff(Z)>0) && ...
            all(isfinite(sws(valid))&sws(valid)>0), ...
            "AdaptiveREQ:FrequencyGrid","Invalid original SWS physical grid.");
        keep=false(size(valid));
        hasMask=jobs.mask_exists(j);
        if hasMask
            B=load(jobs.mask_file(j),"quality_result","mask_identity");
            assert(isfield(B,"quality_result") && isfield(B,"mask_identity"), ...
                "AdaptiveREQ:FrequencyMaskSchema","Saved mask is incomplete.");
            info=jsondecode(char(B.mask_identity));
            Q=B.quality_result;
            assert(isfield(info,"mask_version") && ...
                string(info.mask_version)==MaskVersion && ...
                string(info.source_estimate.path)==jobs.estimate_file(j) && ...
                string(info.source_inference_identity)== ...
                    string(A.inference_identity) && ...
                double(info.frequency_hz)==hz && ...
                double(info.M)==m && ...
                double(info.step_pixels)==StepPixels && ...
                isfield(info,"mask_cutoff") && ...
                abs(double(info.mask_cutoff)-double(Q.cutoff))<1e-12 && ...
                string(info.policy_name)=="validation85_posthoc" && ...
                logical(info.posthoc_secondary) && ...
                string(Q.operating_policy)=="validation85_posthoc" && ...
                abs(double(Q.cutoff)-.2300157481407481)<1e-12 && ...
                isequaln(double(Q.original_sws_map),double(R.cs_map)) && ...
                isequal(double(Q.x_mm(:)),double(R.x_mm(:))) && ...
                isequal(double(Q.z_mm(:)),double(R.z_mm(:))) && ...
                isequal(logical(Q.original_valid_mask),valid) && ...
                isequal(size(Q.masked_sws_map),size(sws)), ...
                "AdaptiveREQ:FrequencyMaskIdentity", ...
                "Mask is not the frozen 85%% policy for this SWS map.");
            keep=logical(Q.retained_mask);
            assert(isequal(keep,valid&isfinite(Q.risk_score_map) & ...
                double(Q.risk_score_map)<=double(Q.cutoff)) && ...
                isequaln(double(Q.masked_sws_map), ...
                    NaNMasked(sws,keep)), ...
                "AdaptiveREQ:FrequencyMaskRule", ...
                "Saved quality map does not reproduce frozen risk decisions.");
        end
        spec=adaptive_req_final_case_rois(id);
        for k=1:numel(spec.rois)
            roi=spec.rois(k);
            % Source ROI names/geometry never changed; only display label.
            if spec.phantom_type=="homogeneous"
                if contains(id,"_5perc_"),material="soft";
                else,material="hard";end
            elseif spec.phantom_type=="bilayer"
                material=string(roi.name);
            elseif spec.phantom_type=="inclusion"
                if string(roi.name)=="inclusion_core",material="hard";
                else,material="soft";end
            else
                error("AdaptiveREQ:FrequencyPhantom","Unknown type.");
            end
            assert(ismember(material,["soft","hard"]), ...
                "AdaptiveREQ:FrequencyMaterial","Unsupported material.");
            c=double(roi.center_mm(:));
            sz=double(roi.size_mm(:));
            within=(Z>=c(2)-sz(2)/2 & Z<=c(2)+sz(2)/2) & ...
                (X>=c(1)-sz(1)/2 & X<=c(1)+sz(1)/2);
            roiPixels=nnz(within);
            originalPixels=nnz(within&valid);
            assert(roiPixels>0, ...
                "AdaptiveREQ:FrequencyROIEmptyGrid", ...
                "Physical ROI %s does not overlap SWS pixel centers.", ...
                string(roi.name));
            for state=["original","masked"]
                if state=="masked" && ~hasMask,continue;end
                choose=valid;
                if state=="masked",choose=keep;end
                y=sws(within&choose);
                n=numel(y);
                mu=NaN;sd=NaN;
                if n>0,mu=mean(y);sd=std(y,0);end
                cov=NaN;
                if originalPixels>0,cov=double(n)/originalPixels;end
                newrow=table(id,jobs.modality(j),spec.phantom_type, ...
                    string(roi.name),material,hz,m,state, ...
                    n,mu,sd,originalPixels,roiPixels,cov, ...
                    'VariableNames',["case_id","modality","phantom_type", ...
                    "roi","material","frequency_hz","M","mask_state", ...
                    "n_valid","mean_sws_m_s","sd_sws_m_s", ...
                    "n_original_valid","roi_pixels","coverage"]);
                rows{end+1,1}=newrow; %#ok<SAGROW>
            end
        end
        statuses(j)="completed";
        if Verbose
            fprintf("[%d/%d] %s | %g Hz | M=%g: ROI stats saved in memory.\n", ...
                j,height(jobs),id,hz,m);
        end
    catch ME
        statuses(j)="failed";
        errors(j)=string(ME.message);
        fprintf(2,"[%d/%d] FAILED %s | %g Hz | M=%g: %s\n", ...
            j,height(jobs),id,hz,m,ME.message);
        if ~ContinueOnError,rethrow(ME);end
    end
end
assert(~isempty(rows),"AdaptiveREQ:FrequencyNoRows", ...
    "No valid ROI statistics; inspect stage-02/03 files and report errors.");
T=vertcat(rows{:});
% Fresh report dir; no original SWS/quality mask files are changed.
stamp=string(datetime("now","Format","yyyyMMdd_HHmmss_SSS"));
out=fullfile(DataRoot,"analysis",StudyID,FigureVersion,stamp);
assert(~isfolder(out),"AdaptiveREQ:FrequencyOutputCollision", ...
    "Refusing to overwrite a previous frequency-figure report.");
mkdir(out);
writetable(T,fullfile(out,"roi_sws_frequency_statistics.csv"));
writetable(reference,fullfile(out,"mechanical_reference_used.csv"));
jobs.status=statuses;
jobs.message=errors;
writetable(jobs,fullfile(out,"input_manifest.csv"));
if ReferenceCSV==""
    fprintf(2,"[REFERENCE WARNING] Bands are APPROXIMATE from REQ main text, NOT the exact per-frequency six-sample extrema.\n");
end
rendered=render_adaptive_req_final_frequency_figures( ...
    T,reference,fullfile(out,"figures"), ...
    MValues=MValues,FrequenciesHz=FrequenciesHz, ...
    Formats=FigureFormats,YLimits=YLimits,Visible=Visible);
fprintf("[DONE] %d figure groups | %d files | %d input errors.\n", ...
    rendered.n_figures,rendered.n_files,nnz(statuses=="failed"));
fprintf("[DONE] Output: %s | elapsed %.2f s.\n",out,toc(runTimer));

%% Local helpers
function target=NaNMasked(sws,mask)
target=sws;
target(~mask)=NaN;
end

function bands=makeMechanicalReference(freqs,csv)
% REQ PMB 2026 manuscript, Fig. 8 and Supplementary Methods.
% True bands: per-Hz extrema across six independent SLS measurements.
% Manuscript's approximate text envelopes are fallback, never called exact.
freqs=sort(double(freqs(:)));
assert(numel(freqs)==numel(unique(freqs)), ...
    "AdaptiveREQ:ReferenceFrequencies","Duplicate selected frequencies.");
if csv~=""
    assert(isfile(csv),"AdaptiveREQ:ReferenceCSV", ...
        "ReferenceCSV not found: %s",csv);
    bands=readtable(csv,TextType="string");
    required=["frequency_hz","material","lower_m_s","upper_m_s"];
    assert(all(ismember(required,string(bands.Properties.VariableNames))), ...
        "AdaptiveREQ:ReferenceSchema", ...
        "Reference CSV must have frequency_hz,material,lower_m_s,upper_m_s.");
    bands=sortrows(bands,["material","frequency_hz"]);
    bands.reference_status=repmat("exact_six_sample_extrema",height(bands),1);
else
    F=[freqs;freqs];
    material=[repmat("soft",numel(freqs),1); ...
        repmat("hard",numel(freqs),1)];
    bands=table(F,material, ...
        [1.8*ones(numel(freqs),1);2.8*ones(numel(freqs),1)], ...
        [2.0*ones(numel(freqs),1);3.2*ones(numel(freqs),1)], ...
        repmat("approximate_main_text_envelope",2*numel(freqs),1), ...
        'VariableNames',["frequency_hz","material","lower_m_s", ...
        "upper_m_s","reference_status"]);
end
assert(height(bands)==numel(freqs)*2 && ...
    all(ismember(string(bands.material),["soft","hard"])) && ...
    all(isfinite(bands.lower_m_s)& ...
        isfinite(bands.upper_m_s)& ...
        bands.lower_m_s>0&bands.upper_m_s>bands.lower_m_s), ...
    "AdaptiveREQ:ReferenceContract","Invalid mechanical reference.");
for mat=["soft","hard"]
    R=bands(bands.material==mat,:);
    assert(height(R)==numel(freqs) && ...
        isequal(sort(double(R.frequency_hz(:))),freqs), ...
        "AdaptiveREQ:ReferencePerFrequency", ...
        "Exactly one mechanical bound per material and frequency required.");
end
end
