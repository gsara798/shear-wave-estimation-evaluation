function report=run_compare_models_500hz(options)
%RUN_COMPARE_MODELS_500HZ Re-run canonical REQ extraction for TWO models.
%
% Compares the exact original stage-02 Full21 output with independently
% inferred clean-trained Full21 and historical reduced-v2 legacy Q0.
% Six Feb 27 acquisitions; default 500 Hz, M=2, step=3; unfiltered.
% Does NOT run IQ processing, train, apply a quality mask or modify Full21.
%
% P=run_compare_models_500hz(Mode="plan"); % read-only
% R=run_compare_models_500hz(Mode="run",UseParallel=true);
%
% Outputs: <case>/estimates/adaptive_req_final_experimental_v1/REQ-ML/
%          <adaptive_req_full21_clean_v1 | legacy_q0_v1>/500Hz/M2/step3/
%          reqml_result.mat
arguments
    options.Mode (1,1) string = "plan"
    options.DataRoot (1,1) string = ""
    options.ReqMLRoot (1,1) string = ""
    options.SelectedCaseIDs (1,:) string = strings(1,0)
    options.FrequencyHz (1,1) double {mustBePositive} = 500
    options.M (1,1) double {mustBePositive} = 2
    options.StepPixels (1,1) double {mustBeInteger,mustBePositive} = 3
    options.UseParallel (1,1) logical = true
    options.Verbose (1,1) logical = true
end
assert(ismember(options.Mode,["plan","run"]), ...
    'Mode must be "plan" or "run".');
cfg=compare_models_500hz_config( ...
    DataRoot=options.DataRoot,ReqMLRoot=options.ReqMLRoot, ...
    SelectedCaseIDs=options.SelectedCaseIDs, ...
    FrequencyHz=options.FrequencyHz,M=options.M, ...
    StepPixels=options.StepPixels);
jobs=cfg.jobs;
modelReady=isfile([cfg.model_original;cfg.model_clean; ...
    cfg.model_legacy;cfg.manifest_legacy]);
fprintf("\n[REQ experimental three-model comparison | %g Hz M=%g step=%d]\n", ...
    options.FrequencyHz,options.M,options.StepPixels);
disp(table(["Full21 original";"Full21 clean"; ...
    "legacy reduced-v2";"legacy manifest"], ...
    modelReady,[cfg.model_original;cfg.model_clean; ...
    cfg.model_legacy;cfg.manifest_legacy], ...
    'VariableNames',["resource","available","path"]));
disp(jobs(:,["case_id","sample_ready","original_ready", ...
    "clean_ready","legacy_ready"]));
report=struct("status","planned","jobs",jobs, ...
    "model_available",all(modelReady), ...
    "output_directory",cfg.output_directory, ...
    "reprocessing_or_training",false,"quality_mask",false);
if options.Mode=="plan"
    fprintf("[PLAN] No MAT data loaded and no files written.\n");
    return
end
assert(all(modelReady), ...
    "Some trained model files/legacy manifest are unavailable (see plan).");
assert(all(jobs.sample_ready & jobs.original_ready), ...
    "All selected processed samples and ORIGINAL Full21 estimates are required.");

addpath(fullfile(cfg.reqml_root,"src"),"-begin");
assert(~isempty(which("reqml.predictSWS")), ...
    "REQ-ML source is not accessible.");

% Load each regressor ONCE. Full21 is evaluated with its canonical
% adaptive_req_full21 branch; Q0 with its original frozen 10 predictors.
C=load(cfg.model_clean,"model","model_info");
assert(isfield(C,"model") && isfield(C,"model_info") && ...
    string(C.model_info.model_id)=="adaptive_req_full21_clean_v1" && ...
    isequal(double(C.model_info.clip_range(:).'),[.001 .999]) && ...
    numel(C.model_info.predictor_names)==21 && ...
    C.model.num_learning_cycles==160 && ...
    C.model.min_leaf_size==2 && ...
    ~C.model_info.validation_used && ~C.model_info.test_used, ...
    "Clean Full21 model differs from frozen clean-only experiment.");
cnames=string(C.model_info.predictor_names(:));
cleanReleaseID="adaptive_req_full21_clean_v1";
cleanRelease=struct("model",C.model, ...
    "req_predictor_names",cnames,"clip_range",[.001 .999], ...
    "manifest",struct("model_id",string(C.model_info.model_id), ...
        "model_predictors",cnames,"release_id",cleanReleaseID), ...
    "model_file",cfg.model_clean,"release_id",cleanReleaseID);
clear C
legacyManifest=jsondecode(fileread(cfg.manifest_legacy));
legacy=reqml.models.loadQ0Model(Model=cfg.model_legacy, ...
    Verbose=options.Verbose);
assert(string(legacyManifest.model_id)=="reqml_q0_reduced_v2" && ...
    isequal(string(legacyManifest.predictor_names(:)), ...
        string(legacy.predictor_names(:))) && ...
    numel(legacy.predictor_names)==10 && ...
    legacy.model.num_learning_cycles==160 && ...
    legacy.model.min_leaf_size==8 && ...
    string(legacy.model_metadata.model_id)== ...
        string(legacyManifest.model_id), ...
    "The selected legacy bundle does not match its reduced-v2 manifest.");

allArms=["adaptive_req_full21_clean_v1","legacy_q0_v1"];
allModelFiles=[cfg.model_clean,cfg.model_legacy];
statuses=strings(height(jobs),2);
messages=strings(height(jobs),2);
elapsed=nan(height(jobs),2);
for j=1:height(jobs)
    job=jobs(j,:);
    fprintf("\n[%d/%d] %s | %g Hz M=%g step=%d\n",j,height(jobs), ...
        job.case_id,job.frequency_hz,job.M,job.step_pixels);
    old=load(job.original_file,"result","inference_identity");
    assert(isfield(old,"result") && isfield(old,"inference_identity"), ...
        "Original stage-02 file lacks saved result and identity: %s", ...
        job.original_file);
    original=old.result;
    assert(isfield(original,"metadata") && ...
        string(original.metadata.experimental_case_id)==job.case_id && ...
        string(original.metadata.experimental_arm)==cfg.arms(1) && ...
        string(original.metadata.experimental_processed_run)==cfg.processed_run && ...
        string(original.metadata.sample_file)==job.sample_file && ...
        double(original.metadata.frequency_hz)==job.frequency_hz && ...
        double(original.metadata.M)==job.M && ...
        double(original.metadata.step_pixels)==job.step_pixels, ...
        "Original Full21 stage-02 result has mismatched settings/source.");

    for k=1:2
        if k==1,output=job.clean_file;else,output=job.legacy_file;end
        arm=allArms(k);
        modelFile=allModelFiles(k);
        fingerprint=struct("case_id",job.case_id, ...
            "frequency_hz",double(job.frequency_hz), ...
            "M",double(job.M),"step_pixels",double(job.step_pixels), ...
            "processed_run",cfg.processed_run, ...
            "arm",arm,"sample",file_identity(job.sample_file), ...
            "model",file_identity(modelFile), ...
            "original_full21",file_identity(job.original_file), ...
            "original_inference_identity",string(old.inference_identity), ...
            "mask_applied",false,"inference_api","reqml.predictSWS");
        if k==2
            fingerprint.training_manifest=file_identity(cfg.manifest_legacy);
        end
        inference_identity=string(jsonencode(fingerprint)); %#ok<NASGU>
        if isfile(output)
            saved=load(output,"inference_identity");
            assert(isfield(saved,"inference_identity") && ...
                string(saved.inference_identity)==inference_identity, ...
                "Existing model output has different provenance: %s",output);
            fprintf("  [%s] REUSED\n",arm);
            statuses(j,k)="reused";
            continue
        end
        partial=output+".partial.mat";
        assert(~isfile(partial), ...
            "Interrupted output exists; inspect before rerun: %s",partial);
        t=tic;
        fprintf("  [%s] Full reqml.predictSWS inference...\n",arm);
        if k==1
            result=reqml.predictSWS(job.sample_file, ...
                Estimator="adaptive_req_full21", ...
                ReleaseBundle=cleanRelease, ...
                M=job.M,StepPixels=job.step_pixels, ...
                CsGuessMPerS=double(original.metadata.cs_guess_m_s), ...
                RequireTruth=false, ...
                UseParallel=options.UseParallel,Verbose=options.Verbose);
        else
            result=reqml.predictSWS(job.sample_file, ...
                ModelBundle=legacy, ...
                M=job.M,StepPixels=job.step_pixels, ...
                CsGuessMPerS=double(original.metadata.cs_guess_m_s), ...
                RequireTruth=false, ...
                UseParallel=options.UseParallel,Verbose=options.Verbose);
        end
        assert(isequal(size(result.cs_map),size(original.cs_map)) && ...
            isequaln(result.x_mm,original.x_mm) && ...
            isequaln(result.z_mm,original.z_mm) && ...
            isequal(string(result.patch_examples.example_id(:)), ...
                string(original.patch_examples.example_id(:))), ...
            "Three-model result has different feature-grid patch centers.");
        result.metadata.experimental_case_id=job.case_id;
        result.metadata.experimental_study_id=cfg.study_id;
        result.metadata.experimental_processed_run=cfg.processed_run;
        result.metadata.experimental_arm=arm;
        result.metadata.experimental_inference_identity=inference_identity;
        result.metadata.experimental_mask_applied=false;
        result.metadata.comparison_reference_file=job.original_file;
        result.metadata.comparison_execution="complete_reqml.predictSWS";
        % The complex per-patch REQ curve is not needed once SWS exists.
        % The result still keeps predictor features, q and coordinate maps.
        if ismember("req_mapping", ...
                string(result.patch_examples.Properties.VariableNames))
            result.patch_examples.req_mapping=[];
        end
        folder=string(fileparts(output));
        if ~isfolder(folder),mkdir(folder);end
        save(partial,"result","inference_identity","-v7.3");
        [ok,msg]=movefile(partial,output);
        assert(ok,"Cannot publish %s: %s",output,msg);
        statuses(j,k)="completed";
        elapsed(j,k)=toc(t);
        fprintf("  [%s] COMPLETED | %.1f%% valid | %.1f seconds\n", ...
            arm,100*nnz(result.valid_mask)/numel(result.valid_mask), ...
            elapsed(j,k));
    end
end
status=table(repelem(string(jobs.case_id),2), ...
    repmat(allArms(:),height(jobs),1), ...
    reshape(statuses.',[],1),reshape(messages.',[],1), ...
    reshape(elapsed.',[],1), ...
    'VariableNames',["case_id","arm","status","message","seconds"]);
report.status="completed";
report.output_manifest=status;
if ~isfolder(cfg.output_directory),mkdir(cfg.output_directory);end
writetable(status,fullfile(cfg.output_directory, ...
    "experimental_inference_summary.csv"));
fprintf("\n[DONE] New estimates saved beside original experimental Full21.\n");
fprintf("  Report: %s\n",cfg.output_directory);
end

function s=file_identity(file)
assert(isfile(file),"Missing fingerprint input: %s",file);
d=dir(file);
assert(numel(d)==1,"Ambiguous file fingerprint: %s",file);
s=struct("path",string(file),"bytes",double(d.bytes), ...
    "datenum",double(d.datenum));
end
